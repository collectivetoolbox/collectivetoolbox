use crate::utilities::*;

/// Location in file payload to inspect.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Offset {
    /// Beginning-of-file absolute offset.
    Bof(u64),
    /// End-of-file negative offset (bytes backwards from end).
    Eof(u64),
    /// Relative offset relative to the end of the previous match level (`&<offset>`).
    Relative(i64),
    /// Indirect offset pointer dereference: `(<offset>.<type>+<adjustment>)`.
    Indirect {
        base: Box<Offset>,
        ind_type: IndirectType,
        adjustment: i64,
        multiplier: i64,
    },
    /// Relative indirect offset pointer dereference: `&(<offset>.<type>+<adjustment>)`.
    RelativeIndirect {
        base: Box<Offset>,
        ind_type: IndirectType,
        adjustment: i64,
        multiplier: i64,
    },
    /// Search within window starting at given offset.
    Search {
        start: u64,
        max_bytes: usize,
    },
}

/// Data type dereferenced by an indirect offset.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IndirectType {
    Byte,
    ShortLe,
    ShortBe,
    LongLe,
    LongBe,
    QuadLe,
    QuadBe,
    Id3Le,
    Id3Be,
}

