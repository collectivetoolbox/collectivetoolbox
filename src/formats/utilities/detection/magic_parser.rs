/// A parsed hierarchical libmagic rule with optional child rules.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HierarchicalMagicRule {
    pub cont_level: usize,
    pub offset: Offset,
    pub test: MagicTest,
    pub description: Option<String>,
    pub mime: Option<String>,
    pub ext: Option<String>,
    pub apple: Option<String>,
    pub strength: u32,
    pub children: Vec<HierarchicalMagicRule>,
}

impl HierarchicalMagicRule {
    /// Constructs a root rule with given offset, test, and description.
    pub fn new_root(offset: Offset, test: MagicTest, description: Option<String>) -> Self {
        Self {
            cont_level: 0,
            offset,
            test,
            description,
            mime: None,
            ext: None,
            apple: None,
            strength: 50,
            children: Vec::new(),
        }
    }
}

/// Decodes escape sequences (e.g. \037\235, \x1f, \n, \r, \t, \ ) from libmagic strings.
pub fn decode_magic_escapes(raw: &str) -> Vec<u8> {
    let mut out = Vec::new();
    let bytes = raw.as_bytes();
    let mut i = 0;

    while i < bytes.len() {
        if let Some(&b'\\') = bytes.get(i) {
            i = i.saturating_add(1);
            if i >= bytes.len() {
                out.push(b'\\');
                break;
            }

            match bytes.get(i) {
                Some(b'n') => {
                    out.push(b'\n');
                    i = i.saturating_add(1);
                }
                Some(b'r') => {
                    out.push(b'\r');
                    i = i.saturating_add(1);
                }
                Some(b't') => {
                    out.push(b'\t');
                    i = i.saturating_add(1);
                }
                Some(b'b') => {
                    out.push(8); // backspace
                    i = i.saturating_add(1);
                }
                Some(b'\\') => {
                    out.push(b'\\');
                    i = i.saturating_add(1);
                }
                Some(b' ') => {
                    out.push(b' ');
                    i = i.saturating_add(1);
                }
                Some(b'x') | Some(b'X') => {
                    i = i.saturating_add(1);
                    let mut hex_str = String::new();
                    for _ in 0..2 {
                        if let Some(&c) = bytes.get(i) {
                            if c.is_ascii_hexdigit() {
                                hex_str.push(char::from(c));
                                i = i.saturating_add(1);
                            } else {
                                break;
                            }
                        }
                    }
                    if let Ok(byte) = u8::from_str_radix(&hex_str, 16) {
                        out.push(byte);
                    }
                }
                Some(&c) if (b'0'..=b'7').contains(&c) => {
                    let mut oct_str = String::new();
                    for _ in 0..3 {
                        if let Some(&oc) = bytes.get(i) {
                            if (b'0'..=b'7').contains(&oc) {
                                oct_str.push(char::from(oc));
                                i = i.saturating_add(1);
                            } else {
                                break;
                            }
                        }
                    }
                    if let Ok(byte) = u8::from_str_radix(&oct_str, 8) {
                        out.push(byte);
                    }
                }
                Some(&other) => {
                    out.push(other);
                    i = i.saturating_add(1);
                }
                None => break,
            }
        } else if let Some(&b) = bytes.get(i) {
            out.push(b);
            i = i.saturating_add(1);
        }
    }

    out
}

/// Splits a libmagic rule line into whitespace-separated tokens, respecting escaped spaces (`\ `).
fn split_magic_tokens(line: &str) -> Vec<String> {
    let mut tokens = Vec::new();
    let mut current = String::new();
    let mut in_escape = false;

    for ch in line.chars() {
        if in_escape {
            current.push(ch);
            in_escape = false;
        } else if ch == '\\' {
            current.push(ch);
            in_escape = true;
        } else if ch.is_whitespace() {
            if !current.is_empty() {
                tokens.push(current);
                current = String::new();
            }
        } else {
            current.push(ch);
        }
    }

    if !current.is_empty() {
        tokens.push(current);
    }

    tokens
}

/// Parses an integer string with decimal, hex (`0x`), or octal (`0`) notation.
fn parse_magic_int(val: &str) -> Option<u64> {
    let trimmed = val.trim();
    if let Some(hex) = trimmed.strip_prefix("0x").or_else(|| trimmed.strip_prefix("0X")) {
        u64::from_str_radix(hex.trim_end_matches(['L', 'h']), 16).ok()
    } else if trimmed.starts_with('0') && trimmed.len() > 1 && trimmed.chars().all(|c| ('0'..='7').contains(&c)) {
        u64::from_str_radix(trimmed, 8).ok()
    } else {
        trimmed.parse::<u64>().ok()
    }
}

/// Parses a signed integer string with optional `+` or `-` prefix.
fn parse_signed_magic_int(val: &str) -> Option<i64> {
    let trimmed = val.trim();
    if let Some(stripped) = trimmed.strip_prefix('-') {
        let u = parse_magic_int(stripped)?;
        let i = i64::try_from(u).ok()?;
        (0i64).checked_sub(i)
    } else if let Some(stripped) = trimmed.strip_prefix('+') {
        let u = parse_magic_int(stripped)?;
        i64::try_from(u).ok()
    } else {
        let u = parse_magic_int(trimmed)?;
        i64::try_from(u).ok()
    }
}

/// Parses an indirect offset specification: `(<offset>.<type>+<adjustment>)`.
fn parse_indirect_offset(raw: &str) -> Option<Offset> {
    let inner = raw.strip_prefix('(')?.strip_suffix(')')?.trim();
    let (before_adj, adjustment) = if let Some(idx) = inner.rfind('+') {
        if idx > 0 {
            let adj = parse_signed_magic_int(inner.get(idx..)?)?;
            (inner.get(..idx)?, adj)
        } else {
            (inner, 0)
        }
    } else if let Some(idx) = inner.rfind('-') {
        if idx > 0 && !inner.ends_with('-') {
            let adj = parse_signed_magic_int(inner.get(idx..)?)?;
            (inner.get(..idx)?, adj)
        } else {
            (inner, 0)
        }
    } else {
        (inner, 0)
    };

    let (base_part, ind_type, multiplier) = if let Some((base_str, type_str)) = before_adj.split_once('.') {
        let type_clean = type_str.trim();
        let (t_str, mult) = if let Some((ts, ms)) = type_clean.split_once('*') {
            (ts.trim(), parse_signed_magic_int(ms).unwrap_or(1))
        } else {
            (type_clean, 1)
        };
        let t = match t_str {
            "b" | "B" | "c" | "C" => IndirectType::Byte,
            "s" | "h" => IndirectType::ShortLe,
            "S" | "H" => IndirectType::ShortBe,
            "l" => IndirectType::LongLe,
            "L" => IndirectType::LongBe,
            "i" => IndirectType::Id3Le,
            "I" => IndirectType::Id3Be,
            "q" | "m" => IndirectType::QuadLe,
            "Q" => IndirectType::QuadBe,
            _ => IndirectType::LongLe,
        };
        (base_str.trim(), t, mult)
    } else {
        (before_adj.trim(), IndirectType::LongLe, 1)
    };

    let base = if let Some(stripped) = base_part.strip_prefix('&') {
        let rel_val = parse_signed_magic_int(stripped)?;
        Offset::Relative(rel_val)
    } else if let Some(stripped) = base_part.strip_prefix('-') {
        let off = parse_magic_int(stripped)?;
        Offset::Eof(off)
    } else {
        let abs_val = parse_magic_int(base_part)?;
        Offset::Bof(abs_val)
    };

    Some(Offset::Indirect {
        base: Box::new(base),
        ind_type,
        adjustment,
        multiplier,
    })
}

/// Parses offset string into an `Offset` enum variant.
pub fn parse_offset(offset_str: &str) -> Option<Offset> {
    let trimmed = offset_str.trim();
    if trimmed.starts_with("&(") && trimmed.ends_with(')') {
        let inner = trimmed.strip_prefix('&')?;
        let ind = parse_indirect_offset(inner)?;
        if let Offset::Indirect { base, ind_type, adjustment, multiplier } = ind {
            Some(Offset::RelativeIndirect { base, ind_type, adjustment, multiplier })
        } else {
            None
        }
    } else if trimmed.starts_with('(') && trimmed.ends_with(')') {
        parse_indirect_offset(trimmed)
    } else if let Some(stripped) = trimmed.strip_prefix('&') {
        let rel_val = parse_signed_magic_int(stripped)?;
        Some(Offset::Relative(rel_val))
    } else if let Some(stripped) = trimmed.strip_prefix('+') {
        let rel_val = parse_signed_magic_int(stripped)?;
        Some(Offset::Relative(rel_val))
    } else if let Some(stripped) = trimmed.strip_prefix('-') {
        let off = parse_magic_int(stripped)?;
        Some(Offset::Eof(off))
    } else {
        let off = parse_magic_int(trimmed)?;
        Some(Offset::Bof(off))
    }
}

/// Parses a 16-byte mixed-endian GUID string e.g. `C1C41626-504C-4092-ACA9-41F936934328`.
fn parse_guid(s: &str) -> Option<[u8; 16]> {
    let clean = s.trim().replace('-', "");
    if clean.len() != 32 {
        return None;
    }
    let d1 = u32::from_str_radix(clean.get(0..8)?, 16).ok()?.to_le_bytes();
    let d2 = u16::from_str_radix(clean.get(8..12)?, 16).ok()?.to_le_bytes();
    let d3 = u16::from_str_radix(clean.get(12..16)?, 16).ok()?.to_le_bytes();
    let mut out = [0u8; 16];
    out[0..4].copy_from_slice(&d1);
    out[4..6].copy_from_slice(&d2);
    out[6..8].copy_from_slice(&d3);
    for (i, chunk) in clean.get(16..32)?.as_bytes().chunks_exact(2).enumerate() {
        let chunk_str = std::str::from_utf8(chunk).ok()?;
        let b = u8::from_str_radix(chunk_str, 16).ok()?;
        let idx = 8usize.saturating_add(i);
        if let Some(slot) = out.get_mut(idx) {
            *slot = b;
        }
    }
    Some(out)
}

fn parse_string_flags(flags_str: Option<&str>) -> StringFlags {
    let mut flags = StringFlags::default();
    if let Some(s) = flags_str {
        flags.case_insensitive = s.contains('c') || s.contains('C');
        flags.blank_insensitive = s.contains('b') || s.contains('B');
        flags.trim = s.contains('t') || s.contains('T');
        flags.compact_whitespace = s.contains('w') || s.contains('W');
    }
    flags
}

fn parse_pstring_flags(flags_str: Option<&str>) -> (PascalLengthSize, bool) {
    let mut size = PascalLengthSize::Byte;
    let mut inc = false;
    if let Some(s) = flags_str {
        if s.contains('H') {
            size = PascalLengthSize::ShortBe;
        } else if s.contains('h') {
            size = PascalLengthSize::ShortLe;
        } else if s.contains('L') {
            size = PascalLengthSize::LongBe;
        } else if s.contains('l') {
            size = PascalLengthSize::LongLe;
        } else if s.contains('B') {
            size = PascalLengthSize::Byte;
        }
        inc = s.contains('J') || s.contains('j');
    }
    (size, inc)
}

fn parse_regex_flags(flags_str: Option<&str>) -> (bool, usize, bool, bool) {
    let mut case_insensitive = false;
    let mut line_mode = false;
    let mut offset_start = false;
    let mut max_bytes = 4096;
    if let Some(s) = flags_str {
        case_insensitive = s.contains('c') || s.contains('C');
        line_mode = s.contains('l') || s.contains('L');
        offset_start = s.contains('s') || s.contains('S');
        let digits: String = s.chars().filter(|c| c.is_ascii_digit()).collect();
        if let Ok(num) = digits.parse::<usize>() {
            if num > 0 {
                if line_mode {
                    max_bytes = num.saturating_mul(8192);
                } else {
                    max_bytes = num;
                }
            }
        }
    }
    (case_insensitive, max_bytes, line_mode, offset_start)
}

fn parse_search_flags(flags_str: Option<&str>) -> (StringFlags, usize) {
    let flags = parse_string_flags(flags_str);
    let mut max_bytes = 65536;
    if let Some(s) = flags_str {
        let digits: String = s.chars().filter(|c| c.is_ascii_digit()).collect();
        if let Ok(num) = digits.parse::<usize>() {
            if num > 0 {
                max_bytes = num;
            }
        }
    }
    (flags, max_bytes)
}

fn convert_regex_octal_escapes(pattern: &str) -> String {
    let mut res = String::with_capacity(pattern.len());
    let mut chars = pattern.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\\' {
            if let Some(&first_digit) = chars.peek() {
                if ('0'..='7').contains(&first_digit) {
                    chars.next();
                    #[allow(clippy::expect_used, reason = "character checked in '0'..='7' so to_digit(8) is infallible")]
                    let mut oct_val = first_digit
                        .to_digit(8)
                        .expect("first_digit in '0'..='7' is valid octal");
                    for _ in 0..2 {
                        if let Some(&d) = chars.peek() {
                            if ('0'..='7').contains(&d) {
                                chars.next();
                                #[allow(clippy::expect_used, reason = "character checked in '0'..='7' so to_digit(8) is infallible")]
                                let d_val = d
                                    .to_digit(8)
                                    .expect("digit in '0'..='7' is valid octal");
                                oct_val = oct_val.saturating_mul(8).saturating_add(d_val);
                            } else {
                                break;
                            }
                        }
                    }
                    if let Ok(byte_val) = u8::try_from(oct_val) {
                        res.push_str(&format!("\\x{:02x}", byte_val));
                    } else {
                        res.push('\\');
                        res.push(first_digit);
                    }
                    continue;
                }
            }
            res.push('\\');
        } else {
            res.push(c);
        }
    }
    res
}


/// Parses a single libmagic rule line into components.
pub fn parse_magic_line(line: &str) -> Option<(usize, Offset, MagicTest, Option<String>)> {
    let trimmed = line.trim();
    if trimmed.is_empty() || trimmed.starts_with('#') || trimmed.starts_with("!:") {
        return None;
    }

    // Determine continuation level
    let mut cont_level: usize = 0;
    let mut rest = trimmed;
    while let Some(stripped) = rest.strip_prefix('>') {
        cont_level = cont_level.saturating_add(1);
        rest = stripped;
    }

    let tokens = split_magic_tokens(rest);
    if tokens.len() < 3 {
        return None;
    }

    let offset_str = match tokens.first() {
        Some(s) => s.as_str(),
        None => return None,
    };
    let type_str = match tokens.get(1) {
        Some(s) => s.as_str(),
        None => return None,
    };
    let val_str = match tokens.get(2) {
        Some(s) => s.as_str(),
        None => return None,
    };

    // Description is the remainder of the line after token 2 with backspace decoding
    let description = if tokens.len() > 3 {
        let raw = tokens.get(3..)?.join(" ");
        let decoded = raw
            .replace(r"\b", "\u{8}")
            .replace(r"\n", "\n")
            .replace(r"\t", "\t");
        Some(decoded)
    } else {
        None
    };

    let offset = parse_offset(offset_str)?;

    // Handle named templates and use invocations
    if type_str == "name" {
        return Some((cont_level, offset, MagicTest::Name(val_str.to_string()), description));
    }
    if type_str == "use" {
        return Some((cont_level, offset, MagicTest::Use(val_str.to_string()), description));
    }
    if type_str == "indirect" {
        return Some((cont_level, offset, MagicTest::Indirect, description));
    }

    // Parse type and optional mask (&...)
    let (type_no_mask, mask_str) = if let Some(idx) = type_str.find('&') {
        let (t, m) = type_str.split_at(idx);
        (t, m.strip_prefix('&'))
    } else {
        (type_str, None)
    };

    // Parse type and optional numeric operator (%N, /N) or string flags (/...)
    let (base_type, flags_str, num_op) = if let Some(idx) = type_no_mask.find('%') {
        let (t, op_str) = type_no_mask.split_at(idx);
        let operand = op_str.strip_prefix('%').and_then(parse_magic_int).unwrap_or(1);
        (t, None, NumOp::Mod(operand))
    } else if let Some(idx) = type_no_mask.find('/') {
        let (t, rest) = type_no_mask.split_at(idx);
        let f = rest.strip_prefix('/').unwrap_or("");
        if f.chars().all(|c| c.is_ascii_digit())
            && !f.is_empty()
            && (t.contains("long") || t.contains("short") || t.contains("byte") || t.contains("quad"))
        {
            let operand = parse_magic_int(f).unwrap_or(1);
            (t, None, NumOp::Div(operand))
        } else {
            (t, Some(f), NumOp::None)
        }
    } else {
        (type_no_mask, None, NumOp::None)
    };

    // Parse type adjustment e.g. leldate+631065600
    let (base_type_no_adj, type_adj) = if let Some(idx) = base_type.find('+') {
        let (t, a) = base_type.split_at(idx);
        let adj = a.strip_prefix('+').and_then(parse_signed_magic_int).unwrap_or(0);
        (t, adj)
    } else if let Some(idx) = base_type.find('-') {
        let (t, a) = base_type.split_at(idx);
        // Reason for fallback: default to zero offset adjustment if negative adjustment is invalid or missing
        let adj = a.strip_prefix('-').and_then(parse_signed_magic_int).map(|v| v.saturating_neg()).unwrap_or(0);
        (t, adj)
    } else {
        (base_type, 0)
    };

    // Parse test
    let test = match base_type_no_adj {
        "string" => {
            let flags = parse_string_flags(flags_str);
            if val_str == "x" {
                MagicTest::StringAny(flags)
            } else if let Some(stripped) = val_str.strip_prefix('>') {
                let bytes = decode_magic_escapes(stripped);
                MagicTest::StringRelOp { pattern: bytes, op: RelOp::Gt, flags }
            } else if let Some(stripped) = val_str.strip_prefix('<') {
                let bytes = decode_magic_escapes(stripped);
                MagicTest::StringRelOp { pattern: bytes, op: RelOp::Lt, flags }
            } else if let Some(stripped) = val_str.strip_prefix('!') {
                let bytes = decode_magic_escapes(stripped);
                MagicTest::StringRelOp { pattern: bytes, op: RelOp::Ne, flags }
            } else if let Some(stripped) = val_str.strip_prefix('=') {
                let bytes = decode_magic_escapes(stripped);
                MagicTest::String { pattern: bytes, flags }
            } else {
                let bytes = decode_magic_escapes(val_str);
                if flags == StringFlags::default() {
                    MagicTest::ExactBytes(bytes)
                } else {
                    MagicTest::String { pattern: bytes, flags }
                }
            }
        }
        "pstring" => {
            let (length_size, length_includes_itself) = parse_pstring_flags(flags_str);
            if val_str == "x" {
                MagicTest::PascalStringAny { length_size, length_includes_itself }
            } else {
                let bytes = decode_magic_escapes(val_str);
                MagicTest::PascalString {
                    pattern: bytes,
                    length_size,
                    length_includes_itself,
                }
            }
        }
        "regex" => {
            let (case_insensitive, max_bytes, line_mode, offset_start) = parse_regex_flags(flags_str);
            let (_, pattern_raw) = parse_op_and_val(val_str);
            let unescaped_pattern = if let Some(stripped) = pattern_raw.strip_prefix(r"\^") {
                format!("^{}", stripped)
            } else if let Some(stripped) = pattern_raw.strip_prefix(r"\<") {
                format!("<{}", stripped)
            } else if let Some(stripped) = pattern_raw.strip_prefix(r"\>") {
                format!(">{}", stripped)
            } else {
                pattern_raw.to_string()
            };
            let converted_pattern = convert_regex_octal_escapes(&unescaped_pattern);
            MagicTest::Regex {
                pattern: converted_pattern,
                case_insensitive,
                max_bytes,
                line_mode,
                offset_start,
            }
        }
        "byte" | "ubyte" => {
            let mask = mask_str.and_then(|m| parse_magic_int(m).and_then(|v| u8::try_from(v).ok()));
            let (op, num_str) = parse_op_and_val(val_str);
            if op == RelOp::Any {
                MagicTest::U8 { value: 0, op: RelOp::Any, mask, num_op }
            } else {
                let val_u64 = parse_magic_int(num_str)?;
                let val = u8::try_from(val_u64).ok()?;
                MagicTest::U8 { value: val, op, mask, num_op }
            }
        }
        "leshort" | "short" | "ushort" | "uleshort" => {
            let mask = mask_str.and_then(|m| parse_magic_int(m).and_then(|v| u16::try_from(v).ok()));
            let (op, num_str) = parse_op_and_val(val_str);
            if op == RelOp::Any {
                MagicTest::U16Le { value: 0, op: RelOp::Any, mask, num_op }
            } else {
                let val_u64 = parse_magic_int(num_str)?;
                let val = u16::try_from(val_u64).ok()?;
                MagicTest::U16Le { value: val, op, mask, num_op }
            }
        }
        "beshort" | "ubeshort" => {
            let mask = mask_str.and_then(|m| parse_magic_int(m).and_then(|v| u16::try_from(v).ok()));
            let (op, num_str) = parse_op_and_val(val_str);
            if op == RelOp::Any {
                MagicTest::U16Be { value: 0, op: RelOp::Any, mask, num_op }
            } else {
                let val_u64 = parse_magic_int(num_str)?;
                let val = u16::try_from(val_u64).ok()?;
                MagicTest::U16Be { value: val, op, mask, num_op }
            }
        }
        "lelong" | "long" | "ulong" | "ulelong" => {
            let mask = mask_str.and_then(|m| parse_magic_int(m).and_then(|v| u32::try_from(v).ok()));
            let (op, num_str) = parse_op_and_val(val_str);
            if op == RelOp::Any {
                MagicTest::U32Le { value: 0, op: RelOp::Any, mask, num_op }
            } else {
                let val_u64 = parse_magic_int(num_str)?;
                let val = u32::try_from(val_u64).ok()?;
                MagicTest::U32Le { value: val, op, mask, num_op }
            }
        }
        "belong" | "ubelong" => {
            let mask = mask_str.and_then(|m| parse_magic_int(m).and_then(|v| u32::try_from(v).ok()));
            let (op, num_str) = parse_op_and_val(val_str);
            if op == RelOp::Any {
                MagicTest::U32Be { value: 0, op: RelOp::Any, mask, num_op }
            } else {
                let val_u64 = parse_magic_int(num_str)?;
                let val = u32::try_from(val_u64).ok()?;
                MagicTest::U32Be { value: val, op, mask, num_op }
            }
        }
        "lequad" | "ulequad" => {
            let mask = mask_str.and_then(parse_magic_int);
            let (op, num_str) = parse_op_and_val(val_str);
            if op == RelOp::Any {
                MagicTest::U64Le { value: 0, op: RelOp::Any, mask, num_op }
            } else {
                let val = parse_magic_int(num_str)?;
                MagicTest::U64Le { value: val, op, mask, num_op }
            }
        }
        "bequad" | "ubequad" | "quad" => {
            let mask = mask_str.and_then(parse_magic_int);
            let (op, num_str) = parse_op_and_val(val_str);
            if op == RelOp::Any {
                MagicTest::U64Be { value: 0, op: RelOp::Any, mask, num_op }
            } else {
                let val = parse_magic_int(num_str)?;
                MagicTest::U64Be { value: val, op, mask, num_op }
            }
        }
        "date" | "bedate" | "ldate" | "beldate" => {
            let (op, num_str) = parse_op_and_val(val_str);
            if op == RelOp::Any {
                MagicTest::Date32Be { value: 0, op: RelOp::Any, adjustment: type_adj }
            } else {
                let val_u64 = parse_magic_int(num_str)?;
                let val = u32::try_from(val_u64).ok()?;
                MagicTest::Date32Be { value: val, op, adjustment: type_adj }
            }
        }
        "ledate" | "leldate" | "medate" => {
            let (op, num_str) = parse_op_and_val(val_str);
            if op == RelOp::Any {
                MagicTest::Date32Le { value: 0, op: RelOp::Any, adjustment: type_adj }
            } else {
                let val_u64 = parse_magic_int(num_str)?;
                let val = u32::try_from(val_u64).ok()?;
                MagicTest::Date32Le { value: val, op, adjustment: type_adj }
            }
        }
        "qdate" | "beqdate" => {
            let (op, num_str) = parse_op_and_val(val_str);
            if op == RelOp::Any {
                MagicTest::Date64Be { value: 0, op: RelOp::Any, adjustment: type_adj }
            } else {
                let val = parse_magic_int(num_str)?;
                MagicTest::Date64Be { value: val, op, adjustment: type_adj }
            }
        }
        "leqdate" => {
            let (op, num_str) = parse_op_and_val(val_str);
            if op == RelOp::Any {
                MagicTest::Date64Le { value: 0, op: RelOp::Any, adjustment: type_adj }
            } else {
                let val = parse_magic_int(num_str)?;
                MagicTest::Date64Le { value: val, op, adjustment: type_adj }
            }
        }
        "lemsdosdate" | "msdosdate" => MagicTest::MsDosDate,
        "lemsdostime" | "msdostime" => MagicTest::MsDosTime,
        "guid" => {
            let g = parse_guid(val_str)?;
            MagicTest::Guid(g)
        }
        "offset" => MagicTest::OffsetVal,
        "default" => MagicTest::Default,
        "clear" => MagicTest::Clear,
        _ if base_type_no_adj.starts_with("search") => {
            let (flags, max_bytes) = parse_search_flags(flags_str);
            let (negated, target_val) = if let Some(stripped) = val_str.strip_prefix('!') {
                (true, stripped)
            } else if let Some(stripped) = val_str.strip_prefix('=') {
                (false, stripped)
            } else {
                (false, val_str)
            };
            let bytes = decode_magic_escapes(target_val);
            MagicTest::Search { pattern: bytes, max_bytes, flags, negated }
        }
        _ => return None,
    };

    Some((cont_level, offset, test, description))
}

fn parse_op_and_val(raw: &str) -> (RelOp, &str) {
    let trimmed = raw.trim();
    if trimmed == "x" {
        (RelOp::Any, "")
    } else if let Some(s) = trimmed.strip_prefix('=') {
        (RelOp::Eq, s.trim())
    } else if let Some(s) = trimmed.strip_prefix('!') {
        (RelOp::Ne, s.trim())
    } else if let Some(s) = trimmed.strip_prefix('>') {
        (RelOp::Gt, s.trim())
    } else if let Some(s) = trimmed.strip_prefix('<') {
        (RelOp::Lt, s.trim())
    } else if let Some(s) = trimmed.strip_prefix('&') {
        (RelOp::BitAnd, s.trim())
    } else if let Some(s) = trimmed.strip_prefix('^') {
        (RelOp::BitClear, s.trim())
    } else {
        (RelOp::Eq, trimmed)
    }
}

/// Calculates rule strength faithful to upstream apprentice_magic_strength_1.
pub fn calculate_rule_strength(test: &MagicTest) -> u32 {
    let mult = 10u32;
    let base = 20u32;
    match test {
        MagicTest::Default => 0,
        MagicTest::Clear | MagicTest::Name(_) | MagicTest::Use(_) | MagicTest::Indirect => 0,
        MagicTest::ExactBytes(b) => base.saturating_add(u32::try_from(b.len()).unwrap_or(0).saturating_mul(mult)),
        MagicTest::MaskedBytes { bytes, .. } => base.saturating_add(u32::try_from(bytes.len()).unwrap_or(0).saturating_mul(mult)),
        MagicTest::String { pattern, .. } => base.saturating_add(u32::try_from(pattern.len()).unwrap_or(0).saturating_mul(mult)),
        MagicTest::StringAny(_) => 0,
        MagicTest::StringRelOp { pattern, .. } => base.saturating_add(u32::try_from(pattern.len()).unwrap_or(0).saturating_mul(mult)),
        MagicTest::PascalString { pattern, .. } => base.saturating_add(u32::try_from(pattern.len()).unwrap_or(0).saturating_mul(mult)),
        MagicTest::PascalStringAny { .. } => 20,
        MagicTest::Search { pattern, .. } => base.saturating_add(u32::try_from(pattern.len()).unwrap_or(0).saturating_mul(mult)),
        MagicTest::Regex { pattern, .. } => base.saturating_add(u32::try_from(pattern.len().min(10)).unwrap_or(0).saturating_mul(mult)),
        MagicTest::U8 { op, .. } => if *op == RelOp::Any { 0 } else { base.saturating_add(10) },
        MagicTest::U16Le { op, .. } | MagicTest::U16Be { op, .. } => if *op == RelOp::Any { 0 } else { base.saturating_add(20) },
        MagicTest::U32Le { op, .. } | MagicTest::U32Be { op, .. } => if *op == RelOp::Any { 0 } else { base.saturating_add(40) },
        MagicTest::U64Le { op, .. } | MagicTest::U64Be { op, .. } => if *op == RelOp::Any { 0 } else { base.saturating_add(80) },
        MagicTest::Date32Le { op, .. } | MagicTest::Date32Be { op, .. } => if *op == RelOp::Any { 0 } else { base.saturating_add(40) },
        MagicTest::Date64Le { op, .. } | MagicTest::Date64Be { op, .. } => if *op == RelOp::Any { 0 } else { base.saturating_add(80) },
        MagicTest::Guid(_) => base.saturating_add(160),
        MagicTest::MsDosDate | MagicTest::MsDosTime | MagicTest::OffsetVal => base.saturating_add(20),
    }
}

/// Parses an entire libmagic file content into hierarchical root rules and named templates.
pub fn parse_magic_content_with_templates(
    content: &str,
) -> (Vec<HierarchicalMagicRule>, std::collections::HashMap<String, HierarchicalMagicRule>) {
    let mut root_rules = Vec::new();
    let mut named_templates: std::collections::HashMap<String, HierarchicalMagicRule> =
        std::collections::HashMap::new();
    let mut stack: Vec<HierarchicalMagicRule> = Vec::new();
    let mut current_template_name: Option<String> = None;

    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }

        // Check directives: !:mime, !:ext, !:apple, !:strength
        if let Some(directive) = trimmed.strip_prefix("!:") {
            let parts: Vec<&str> = directive.splitn(2, char::is_whitespace).collect();
            let name = parts.first().copied().unwrap_or("");
            let val = parts.get(1).copied().unwrap_or("").trim();

            if let Some(target) = stack.last_mut() {
                match name {
                    "mime" => target.mime = Some(val.to_string()),
                    "ext" => target.ext = Some(val.to_string()),
                    "apple" => target.apple = Some(val.to_string()),
                    "strength" => {
                        let clean = val.replace(' ', "");
                        if let Some(root_target) = stack.first_mut() {
                            if let Some(rest) = clean.strip_prefix('+') {
                                if let Ok(delta) = rest.parse::<u32>() {
                                    root_target.strength = root_target.strength.saturating_add(delta);
                                }
                            } else if let Some(rest) = clean.strip_prefix('-') {
                                if let Ok(delta) = rest.parse::<u32>() {
                                    root_target.strength = root_target.strength.saturating_sub(delta);
                                }
                            } else if let Some(rest) = clean.strip_prefix('*') {
                                if let Ok(factor) = rest.parse::<u32>() {
                                    root_target.strength = root_target.strength.saturating_mul(factor);
                                }
                            } else if let Some(rest) = clean.strip_prefix('/') {
                                if let Ok(div) = rest.parse::<u32>() {
                                    if div != 0 {
                                        root_target.strength = root_target.strength.checked_div(div).unwrap_or(root_target.strength);
                                    }
                                }
                            } else if let Ok(s) = clean.parse::<u32>() {
                                root_target.strength = s;
                            }
                        }
                    }
                    _ => {}
                }
            }
            continue;
        }

        let Some((level, offset, test, description)) = parse_magic_line(trimmed) else {
            continue;
        };

        let initial_strength = calculate_rule_strength(&test);
        let new_rule = HierarchicalMagicRule {
            cont_level: level,
            offset,
            test,
            description,
            mime: None,
            ext: None,
            apple: None,
            strength: initial_strength,
            children: Vec::new(),
        };

        if level == 0 {
            // Pop entire stack and store in root_rules or named_templates
            if let Some(root) = collapse_stack(&mut stack) {
                if let Some(tpl_name) = current_template_name.take() {
                    named_templates.insert(tpl_name, root);
                } else {
                    root_rules.push(root);
                }
            }

            if let MagicTest::Name(ref tpl_name) = new_rule.test {
                current_template_name = Some(tpl_name.clone());
            } else {
                current_template_name = None;
            }

            stack.push(new_rule);
        } else {
            if stack.is_empty() {
                continue;
            }
            while stack.len() > level {
                let popped = match stack.pop() {
                    Some(p) => p,
                    None => break,
                };
                if let Some(parent) = stack.last_mut() {
                    parent.children.push(popped);
                }
            }
            stack.push(new_rule);
        }
    }

    if let Some(root) = collapse_stack(&mut stack) {
        if let Some(tpl_name) = current_template_name.take() {
            named_templates.insert(tpl_name, root);
        } else {
            root_rules.push(root);
        }
    }

    (root_rules, named_templates)
}

/// Parses an entire libmagic file content into a list of hierarchical root rules.
pub fn parse_magic_content(content: &str) -> Vec<HierarchicalMagicRule> {
    parse_magic_content_with_templates(content).0
}

fn collapse_stack(stack: &mut Vec<HierarchicalMagicRule>) -> Option<HierarchicalMagicRule> {
    while stack.len() > 1 {
        let child = stack.pop()?;
        if let Some(parent) = stack.last_mut() {
            parent.children.push(child);
        }
    }
    stack.pop()
}

