/// Trims trailing NUL bytes while preserving parity for UTF-16 character boundaries.
/// Ported from `trim_nuls` in `ascmagic.c`.
#[must_use]
pub fn trim_nuls(buf: &[u8]) -> &[u8] {
    let mut len = buf.len();
    while len > 1 && buf.get(len.saturating_sub(1)) == Some(&0) {
        len = len.saturating_sub(1);
    }
    // Avoid trimming at an odd byte if original buffer was evenly sized;
    // this avoids losing the last character on UTF-16 LE text.
    let rem = len.checked_rem(2);
    let buf_rem = buf.len().checked_rem(2);
    if rem == Some(1) && buf_rem == Some(0) && len < buf.len() {
        len = len.saturating_add(1);
    }
    // Reason for fallback: slice indexing within validated bounds never fails
    buf.get(..len).unwrap_or(buf)
}

/// Checks whether `buf` consists solely of valid 7-bit ASCII text characters.
#[must_use]
pub fn looks_ascii(buf: &[u8]) -> bool {
    if buf.is_empty() {
        return false;
    }
    buf.iter().all(|&b| {
        // Reason for fallback: index within 0..=255 bounds is always valid
        let cls = TEXT_CHARS.get(usize::from(b)).copied().unwrap_or(CHAR_F);
        cls == CHAR_T
    })
}

/// Evaluates whether `buf` is valid UTF-8 text.
#[must_use]
pub fn looks_utf8(buf: &[u8]) -> Option<(IdentifiedEncoding, bool)> {
    if buf.len() < 2 {
        return None;
    }
    let with_bom = buf.starts_with(b"\xEF\xBB\xBF");
    let content = if with_bom {
        // Reason for fallback: slice indexing with verified prefix length is valid
        buf.get(3..).unwrap_or(&[])
    } else {
        buf
    };

    if content.is_empty() {
        if with_bom {
            return Some((IdentifiedEncoding::Utf8 { with_bom: true }, true));
        }
        return None;
    }

    // Try decoding up to the largest valid UTF-8 prefix in case of cut-off
    let mut valid_end = content.len();
    let mut s_res = std::str::from_utf8(content);
    if let Err(err) = s_res {
        let valid_up_to = err.valid_up_to();
        if valid_up_to > 0 && err.error_len().is_none() {
            // Cut-off at end of buffer
            valid_end = valid_up_to;
            s_res = std::str::from_utf8(content.get(..valid_end).unwrap_or(&[]));
        } else {
            return None;
        }
    }

    let Ok(s) = s_res else {
        return None;
    };

    let mut has_multibyte = false;
    for ch in s.chars() {
        let codepoint = u32::from(ch);
        if codepoint < 128 {
            let Ok(b) = u8::try_from(codepoint) else {
                return None;
            };
            // Reason for fallback: index within 0..=255 bounds is always valid
            let cls = TEXT_CHARS.get(usize::from(b)).copied().unwrap_or(CHAR_F);
            if cls != CHAR_T {
                return None;
            }
        } else {
            has_multibyte = true;
        }
    }

    if with_bom {
        Some((IdentifiedEncoding::Utf8 { with_bom: true }, has_multibyte))
    } else if has_multibyte {
        Some((IdentifiedEncoding::Utf8 { with_bom: false }, true))
    } else {
        Some((IdentifiedEncoding::Ascii, false))
    }
}

/// Evaluates whether `buf` is UTF-16 text (with or without BOM, LE or BE).
#[must_use]
pub fn looks_utf16(buf: &[u8]) -> Option<IdentifiedEncoding> {
    if buf.len() < 2 {
        return None;
    }

    // Check BOM
    if buf.len() >= 2 {
        let first = buf.first().copied();
        let second = buf.get(1).copied();
        if first == Some(0xFF) && second == Some(0xFE) {
            // Ensure not UTF-32LE BOM (FF FE 00 00)
            let third = buf.get(2).copied();
            let fourth = buf.get(3).copied();
            if third != Some(0x00) || fourth != Some(0x00) {
                if validate_utf16_content(buf.get(2..).unwrap_or(&[]), false) {
                    return Some(IdentifiedEncoding::Utf16Le { with_bom: true });
                }
            }
        } else if first == Some(0xFE) && second == Some(0xFF) {
            if validate_utf16_content(buf.get(2..).unwrap_or(&[]), true) {
                return Some(IdentifiedEncoding::Utf16Be { with_bom: true });
            }
        }
    }

    // Without BOM: check whether it looks like UTF-16
    if buf.len() >= 4 {
        let inspect_len = buf.len().saturating_sub(buf.len().checked_rem(2).unwrap_or(0));
        let slice = buf.get(..inspect_len).unwrap_or(buf);

        // Check if even or odd bytes are predominantly 0x00 for ASCII ranges
        let mut even_zeros = 0usize;
        let mut odd_zeros = 0usize;
        let pairs = slice.len().checked_div(2).unwrap_or(0);
        if pairs >= 2 {
            for i in 0..pairs {
                let idx0 = i.saturating_mul(2);
                let idx1 = idx0.saturating_add(1);
                if slice.get(idx0) == Some(&0) {
                    even_zeros = even_zeros.saturating_add(1);
                }
                if slice.get(idx1) == Some(&0) {
                    odd_zeros = odd_zeros.saturating_add(1);
                }
            }

            // UTF-16 LE: odd bytes are mostly 0 for ASCII text
            let odd_ratio = odd_zeros.saturating_mul(100).checked_div(pairs).unwrap_or(0);
            if odd_ratio >= 40 && validate_utf16_content(slice, false) {
                return Some(IdentifiedEncoding::Utf16Le { with_bom: false });
            }

            // UTF-16 BE: even bytes are mostly 0 for ASCII text
            let even_ratio = even_zeros.saturating_mul(100).checked_div(pairs).unwrap_or(0);
            if even_ratio >= 40 && validate_utf16_content(slice, true) {
                return Some(IdentifiedEncoding::Utf16Be { with_bom: false });
            }
        }
    }

    None
}

/// Helper validating UTF-16 code units, surrogates, and text characters.
fn validate_utf16_content(buf: &[u8], big_endian: bool) -> bool {
    let pairs = buf.len().checked_div(2).unwrap_or(0);
    if pairs == 0 {
        return true;
    }

    let mut hi_surrogate: Option<u32> = None;
    let mut valid_chars = 0usize;

    for i in 0..pairs {
        let idx0 = i.saturating_mul(2);
        let idx1 = idx0.saturating_add(1);
        let b0 = buf.get(idx0).copied().unwrap_or(0);
        let b1 = buf.get(idx1).copied().unwrap_or(0);

        let uc = if big_endian {
            u32::from(b1) | (u32::from(b0) << 8)
        } else {
            u32::from(b0) | (u32::from(b1) << 8)
        };

        // Reject non-characters
        if uc == 0xFFFE || uc == 0xFFFF || (0xFDD0..=0xFDEF).contains(&uc) {
            return false;
        }

        if let Some(hi) = hi_surrogate {
            // Must be low surrogate
            if !(0xDC00..=0xDFFF).contains(&uc) {
                return false;
            }
            hi_surrogate = None;
            valid_chars = valid_chars.saturating_add(1);
            continue;
        }

        if (0xD800..=0xDBFF).contains(&uc) {
            hi_surrogate = Some(uc);
            continue;
        } else if (0xDC00..=0xDFFF).contains(&uc) {
            // Low surrogate without high surrogate
            return false;
        }

        if uc < 128 {
            let Ok(byte_val) = u8::try_from(uc) else {
                return false;
            };
            // Reason for fallback: index within 0..=255 bounds is always valid
            let cls = TEXT_CHARS.get(usize::from(byte_val)).copied().unwrap_or(CHAR_F);
            if cls != CHAR_T && byte_val != 0 {
                return false;
            }
        }

        valid_chars = valid_chars.saturating_add(1);
    }

    hi_surrogate.is_none() && valid_chars > 0
}

/// Evaluates whether `buf` is UTF-32 text (with or without BOM, LE or BE).
#[must_use]
pub fn looks_utf32(buf: &[u8]) -> Option<IdentifiedEncoding> {
    if buf.len() < 4 {
        return None;
    }

    // Check BOM
    if buf.len() >= 4 {
        let b0 = buf.first().copied();
        let b1 = buf.get(1).copied();
        let b2 = buf.get(2).copied();
        let b3 = buf.get(3).copied();

        if b0 == Some(0xFF) && b1 == Some(0xFE) && b2 == Some(0x00) && b3 == Some(0x00) {
            if validate_utf32_content(buf.get(4..).unwrap_or(&[]), false) {
                return Some(IdentifiedEncoding::Utf32Le { with_bom: true });
            }
        } else if b0 == Some(0x00) && b1 == Some(0x00) && b2 == Some(0xFE) && b3 == Some(0xFF) {
            if validate_utf32_content(buf.get(4..).unwrap_or(&[]), true) {
                return Some(IdentifiedEncoding::Utf32Be { with_bom: true });
            }
        }
    }

    // Without BOM
    if buf.len() >= 8 {
        let inspect_len = buf.len().saturating_sub(buf.len().checked_rem(4).unwrap_or(0));
        let slice = buf.get(..inspect_len).unwrap_or(buf);
        let quads = slice.len().checked_div(4).unwrap_or(0);

        if quads >= 2 {
            let mut le_matches = 0usize;
            let mut be_matches = 0usize;

            for i in 0..quads {
                let idx = i.saturating_mul(4);
                let b0 = slice.get(idx).copied().unwrap_or(0);
                let b1 = slice.get(idx.saturating_add(1)).copied().unwrap_or(0);
                let b2 = slice.get(idx.saturating_add(2)).copied().unwrap_or(0);
                let b3 = slice.get(idx.saturating_add(3)).copied().unwrap_or(0);

                if b1 == 0 && b2 == 0 && b3 == 0 && b0 > 0 && b0 < 128 {
                    le_matches = le_matches.saturating_add(1);
                }
                if b0 == 0 && b1 == 0 && b2 == 0 && b3 > 0 && b3 < 128 {
                    be_matches = be_matches.saturating_add(1);
                }
            }

            let le_ratio = le_matches.saturating_mul(100).checked_div(quads).unwrap_or(0);
            if le_ratio >= 40 && validate_utf32_content(slice, false) {
                return Some(IdentifiedEncoding::Utf32Le { with_bom: false });
            }

            let be_ratio = be_matches.saturating_mul(100).checked_div(quads).unwrap_or(0);
            if be_ratio >= 40 && validate_utf32_content(slice, true) {
                return Some(IdentifiedEncoding::Utf32Be { with_bom: false });
            }
        }
    }

    None
}

/// Helper validating UTF-32 code units.
fn validate_utf32_content(buf: &[u8], big_endian: bool) -> bool {
    let quads = buf.len().checked_div(4).unwrap_or(0);
    if quads == 0 {
        return true;
    }

    for i in 0..quads {
        let idx = i.saturating_mul(4);
        let b0 = buf.get(idx).copied().unwrap_or(0);
        let b1 = buf.get(idx.saturating_add(1)).copied().unwrap_or(0);
        let b2 = buf.get(idx.saturating_add(2)).copied().unwrap_or(0);
        let b3 = buf.get(idx.saturating_add(3)).copied().unwrap_or(0);

        let uc = if big_endian {
            u32::from(b3) | (u32::from(b2) << 8) | (u32::from(b1) << 16) | (u32::from(b0) << 24)
        } else {
            u32::from(b0) | (u32::from(b1) << 8) | (u32::from(b2) << 16) | (u32::from(b3) << 24)
        };

        if uc > 0x0010_FFFF || (0xD800..=0xDFFF).contains(&uc) || uc == 0xFFFE || uc == 0xFFFF {
            return false;
        }

        if uc < 128 {
            let Ok(byte_val) = u8::try_from(uc) else {
                return false;
            };
            // Reason for fallback: index within 0..=255 bounds is always valid
            let cls = TEXT_CHARS.get(usize::from(byte_val)).copied().unwrap_or(CHAR_F);
            if cls != CHAR_T && byte_val != 0 {
                return false;
            }
        }
    }

    true
}

/// Evaluates whether `buf` is ISO-8859 text (characters in ASCII text or 0xA0..=0xFF).
#[must_use]
pub fn looks_iso8859(buf: &[u8]) -> Option<IdentifiedEncoding> {
    if buf.is_empty() {
        return None;
    }
    let mut has_high = false;
    for &b in buf {
        // Reason for fallback: index within 0..=255 bounds is always valid
        let cls = TEXT_CHARS.get(usize::from(b)).copied().unwrap_or(CHAR_F);
        if cls == CHAR_I {
            has_high = true;
        } else if cls != CHAR_T {
            return None;
        }
    }
    if has_high {
        Some(IdentifiedEncoding::Iso8859_1)
    } else {
        Some(IdentifiedEncoding::Ascii)
    }
}

/// Evaluates whether `buf` is non-ISO 8-bit extended ASCII (CP437, MacRoman, Windows-1252).
#[must_use]
pub fn looks_extended_ascii(buf: &[u8]) -> Option<IdentifiedEncoding> {
    if buf.is_empty() {
        return None;
    }
    let mut has_extended = false;
    for &b in buf {
        // Reason for fallback: index within 0..=255 bounds is always valid
        let cls = TEXT_CHARS.get(usize::from(b)).copied().unwrap_or(CHAR_F);
        if cls == CHAR_X {
            has_extended = true;
        } else if cls != CHAR_T && cls != CHAR_I {
            return None;
        }
    }

    if has_extended {
        // Evaluate likelihood of Windows-1252 vs MacRoman vs CP437
        // Windows-1252 has unused bytes at 0x81, 0x8D, 0x8F, 0x90, 0x9D
        let has_win_unused = buf.iter().any(|&b| matches!(b, 0x81 | 0x8D | 0x8F | 0x90 | 0x9D));
        if !has_win_unused {
            Some(IdentifiedEncoding::ExtendedAscii(CharEncoding::windows_1252()))
        } else {
            Some(IdentifiedEncoding::ExtendedAscii(CharEncoding::cp437()))
        }
    } else {
        None
    }
}

/// Evaluates whether `buf` is EBCDIC text using the POSIX dd translation table.
#[must_use]
pub fn looks_ebcdic(buf: &[u8]) -> Option<IdentifiedEncoding> {
    if buf.len() < 2 {
        return None;
    }

    let mut is_ascii = true;
    let mut is_international = true;

    for &b in buf {
        // Reason for fallback: index within 0..=255 bounds is always valid
        let translated = EBCDIC_TO_ASCII.get(usize::from(b)).copied().unwrap_or(0);
        let cls = TEXT_CHARS.get(usize::from(translated)).copied().unwrap_or(CHAR_F);
        if cls != CHAR_T {
            is_ascii = false;
            if cls != CHAR_I {
                is_international = false;
                break;
            }
        }
    }

    if is_ascii {
        Some(IdentifiedEncoding::Ebcdic)
    } else if is_international {
        Some(IdentifiedEncoding::InternationalEbcdic)
    } else {
        None
    }
}

/// Identifies the character set encoding family of `data`.
/// Ported from `file_encoding` in `encoding.c`.
#[must_use]
pub fn detect_text_encoding(data: &[u8]) -> Option<IdentifiedEncoding> {
    let trimmed = trim_nuls(data);
    if trimmed.len() < 2 {
        return None;
    }

    // 1. 7-bit ASCII
    if looks_ascii(trimmed) {
        return Some(IdentifiedEncoding::Ascii);
    }

    // 2. UTF-8 (with BOM or valid multibyte sequences)
    if let Some((enc, _)) = looks_utf8(trimmed) {
        return Some(enc);
    }

    // 3. UTF-32 (UCS-4)
    if let Some(enc) = looks_utf32(trimmed) {
        return Some(enc);
    }

    // 4. UTF-16 (UCS-2)
    if let Some(enc) = looks_utf16(trimmed) {
        return Some(enc);
    }

    // 5. ISO-8859 (Latin-1)
    if let Some(enc) = looks_iso8859(trimmed) {
        return Some(enc);
    }

    // 6. Non-ISO 8-bit extended ASCII
    if let Some(enc) = looks_extended_ascii(trimmed) {
        return Some(enc);
    }

    // 7. EBCDIC
    if let Some(enc) = looks_ebcdic(trimmed) {
        return Some(enc);
    }

    None
}

/// Profiles text layout conventions, line endings, long lines, and escape sequences.
/// Ported from `file_ascmagic_with_encoding` in `ascmagic.c`.
#[must_use]
pub fn profile_text_layout(data: &[u8], encoding: IdentifiedEncoding) -> TextProfile {
    let trimmed = trim_nuls(data);

    let mut n_lf = 0usize;
    let mut n_cr = 0usize;
    let mut n_crlf = 0usize;
    let mut n_nel = 0usize;

    let mut seen_cr = false;
    let mut has_escapes = false;
    let mut has_backspace = false;

    let mut max_line_length = 0usize;
    let mut current_line_len = 0usize;

    // Decode or scan characters based on encoding
    match encoding {
        IdentifiedEncoding::Utf16Le { .. } | IdentifiedEncoding::Utf16Be { .. } => {
            let big_end = matches!(encoding, IdentifiedEncoding::Utf16Be { .. });
            let offset = if data.starts_with(b"\xFF\xFE") || data.starts_with(b"\xFE\xFF") {
                2usize
            } else {
                0usize
            };
            let pairs = trimmed.get(offset..).unwrap_or(&[]).len().checked_div(2).unwrap_or(0);
            for i in 0..pairs {
                let idx0 = offset.saturating_add(i.saturating_mul(2));
                let idx1 = idx0.saturating_add(1);
                let b0 = trimmed.get(idx0).copied().unwrap_or(0);
                let b1 = trimmed.get(idx1).copied().unwrap_or(0);
                let uc = if big_end {
                    u32::from(b1) | (u32::from(b0) << 8)
                } else {
                    u32::from(b0) | (u32::from(b1) << 8)
                };
                process_char_for_layout(
                    uc,
                    &mut seen_cr,
                    &mut n_lf,
                    &mut n_cr,
                    &mut n_crlf,
                    &mut n_nel,
                    &mut has_escapes,
                    &mut has_backspace,
                    &mut current_line_len,
                    &mut max_line_length,
                );
            }
        }
        IdentifiedEncoding::Ebcdic | IdentifiedEncoding::InternationalEbcdic => {
            for &b in trimmed {
                // Reason for fallback: index within 0..=255 bounds is always valid
                let translated = EBCDIC_TO_ASCII.get(usize::from(b)).copied().unwrap_or(0);
                process_char_for_layout(
                    u32::from(translated),
                    &mut seen_cr,
                    &mut n_lf,
                    &mut n_cr,
                    &mut n_crlf,
                    &mut n_nel,
                    &mut has_escapes,
                    &mut has_backspace,
                    &mut current_line_len,
                    &mut max_line_length,
                );
            }
        }
        _ => {
            // ASCII, UTF-8, ISO-8859, Extended ASCII
            let content = if trimmed.starts_with(b"\xEF\xBB\xBF") {
                trimmed.get(3..).unwrap_or(&[])
            } else {
                trimmed
            };
            for &b in content {
                process_char_for_layout(
                    u32::from(b),
                    &mut seen_cr,
                    &mut n_lf,
                    &mut n_cr,
                    &mut n_crlf,
                    &mut n_nel,
                    &mut has_escapes,
                    &mut has_backspace,
                    &mut current_line_len,
                    &mut max_line_length,
                );
            }
        }
    }

    if seen_cr && n_cr == 0 && n_crlf == 0 {
        n_cr = n_cr.saturating_add(1);
    }
    max_line_length = max_line_length.max(current_line_len);

    let has_long_lines = max_line_length > MAX_LINE_LENGTH;

    // Determine primary line ending convention
    let primary_line_ending = if n_crlf >= n_lf && n_crlf >= n_cr && n_crlf > 0 {
        Some(LineEndingKind::CrLf)
    } else if n_lf >= n_cr && n_lf > 0 {
        Some(LineEndingKind::Lf)
    } else if n_cr > 0 {
        Some(LineEndingKind::Cr)
    } else if n_nel > 0 {
        Some(LineEndingKind::Nl)
    } else {
        None
    };

    let syntax = detect_text_syntax(trimmed);

    TextProfile {
        encoding,
        primary_line_ending,
        n_lf,
        n_crlf,
        n_cr,
        n_nel,
        has_long_lines,
        max_line_length,
        has_escapes,
        has_backspace,
        syntax,
    }
}

/// Helper updating layout counters for a single decoded character code.
#[allow(
    clippy::too_many_arguments,
    reason = "Layout counters are tracked individually for accurate newline profiling"
)]
fn process_char_for_layout(
    uc: u32,
    seen_cr: &mut bool,
    n_lf: &mut usize,
    n_cr: &mut usize,
    n_crlf: &mut usize,
    n_nel: &mut usize,
    has_escapes: &mut bool,
    has_backspace: &mut bool,
    current_line_len: &mut usize,
    max_line_length: &mut usize,
) {
    if uc == 0x0A {
        // '\n'
        if *seen_cr {
            *n_crlf = n_crlf.saturating_add(1);
        } else {
            *n_lf = n_lf.saturating_add(1);
        }
        *seen_cr = false;
        *max_line_length = (*max_line_length).max(*current_line_len);
        *current_line_len = 0;
    } else {
        if *seen_cr {
            *n_cr = n_cr.saturating_add(1);
            *max_line_length = (*max_line_length).max(*current_line_len);
            *current_line_len = 0;
        }
        *seen_cr = uc == 0x0D; // '\r'

        if uc == 0x85 {
            // NEL
            *n_nel = n_nel.saturating_add(1);
            *max_line_length = (*max_line_length).max(*current_line_len);
            *current_line_len = 0;
        } else if uc != 0x0D {
            *current_line_len = current_line_len.saturating_add(1);
        }

        if uc == 0x1B {
            *has_escapes = true;
        }
        if uc == 0x08 {
            *has_backspace = true;
        }
    }
}

/// Detects programming languages, markup formats, and syntax patterns.
#[must_use]
pub fn detect_text_syntax(data: &[u8]) -> Option<TextSyntaxKind> {
    // 1. Shebang (`#!`) interpreter extraction
    if data.starts_with(b"#!") {
        if let Some(shebang) = extract_shebang(data) {
            return Some(shebang);
        }
    }

    // Convert sample prefix to string for text searches
    let sample_len = data.len().min(8192);
    // Reason for fallback: slice indexing within validated min bound is always valid
    let sample_bytes = data.get(..sample_len).unwrap_or(data);
    let sample = String::from_utf8_lossy(sample_bytes);

    // 2. XML declaration: <?xml
    let trimmed_sample = sample.trim_start();
    if trimmed_sample.starts_with("<?xml") {
        return Some(TextSyntaxKind::XmlDocument);
    }

    // 3. HTML heuristics
    let sample_lower = sample.to_ascii_lowercase();
    if sample_lower.contains("<!doctype html")
        || sample_lower.contains("<html")
        || (sample_lower.contains("<head") && sample_lower.contains("<body"))
    {
        return Some(TextSyntaxKind::HtmlDocument);
    }

    // 4. SGML declaration
    if trimmed_sample.starts_with("<!doctype ") || trimmed_sample.starts_with("<!sgml") {
        return Some(TextSyntaxKind::SgmlDocument);
    }

    // 5. roff/troff commands (.TH, .SH, .PP at start of line)
    for line in sample.lines().take(10) {
        let t = line.trim_start();
        if t.starts_with(".TH ") || t.starts_with(".so ") || t.starts_with(".SH ") || t.starts_with(".PP") {
            return Some(TextSyntaxKind::RoffDocument);
        }
    }

    // 6. TeX / LaTeX heuristics
    if sample.contains("\\documentclass")
        || sample.contains("\\begin{document}")
        || sample.contains("\\usepackage{")
    {
        return Some(TextSyntaxKind::TeXDocument);
    }

    // 7. RFC 822 / Mail / News header heuristics
    if sample.starts_with("From: ")
        || sample.starts_with("Received: ")
        || (sample.contains("\nFrom: ") && sample.contains("\nSubject: "))
        || (sample.contains("\nFrom: ") && sample.contains("\nDate: "))
    {
        return Some(TextSyntaxKind::MailOrNewsHeader);
    }

    // 8. C / C++ heuristics
    let has_c_include = sample.contains("#include <") || sample.contains("#include \"");
    let has_c_main = sample.contains("int main(") || sample.contains("void main(");
    let has_c_define = sample.contains("#define ") || sample.contains("#ifdef ") || sample.contains("#ifndef ");
    let has_cpp_features = sample.contains("namespace ")
        || sample.contains("std::")
        || sample.contains("class ")
        || sample.contains("template<")
        || sample.contains("cout <<")
        || sample.contains("#include <iostream>")
        || sample.contains("#include <vector>");

    if (has_c_include && (has_c_main || has_c_define)) || (has_c_main && has_c_define) {
        if has_cpp_features {
            return Some(TextSyntaxKind::CppSource);
        }
        return Some(TextSyntaxKind::CSource);
    }

    // 9. Python heuristics
    let has_py_def = sample.contains("def ") && sample.contains(":\n");
    let has_py_import = sample.contains("import ") || sample.contains("from ");
    let has_py_dunder = sample.contains("__name__ == '__main__'") || sample.contains("__name__ == \"__main__\"");
    let has_py_triple = sample.contains("\"\"\"") || sample.contains("'''");
    if (has_py_def && has_py_import) || (has_py_dunder && has_py_import) || (has_py_def && has_py_triple) {
        return Some(TextSyntaxKind::PythonScript);
    }

    // 10. Shell script heuristics
    let has_sh_fi = sample.contains("if [ ") && sample.contains("then") && sample.contains("fi");
    let has_sh_case = sample.contains("case ") && sample.contains(" in\n") && sample.contains("esac");
    let has_sh_export = sample.contains("export ") && (sample.contains("echo ") || sample.contains("exit "));
    if has_sh_fi || has_sh_case || has_sh_export {
        return Some(TextSyntaxKind::ShellScript);
    }

    // 11. Perl heuristics
    let has_perl_strict = sample.contains("use strict;") || sample.contains("use warnings;");
    let has_perl_my = sample.contains("my $") && sample.contains("sub ");
    if has_perl_strict || has_perl_my {
        return Some(TextSyntaxKind::PerlScript);
    }

    // 12. Ruby heuristics
    let has_ruby_def = sample.contains("def ") && sample.contains("\nend");
    let has_ruby_require = sample.contains("require '") || sample.contains("require \"");
    let has_ruby_attr = sample.contains("attr_accessor") || sample.contains("attr_reader");
    if (has_ruby_def && has_ruby_require) || has_ruby_attr {
        return Some(TextSyntaxKind::RubySource);
    }

    // 13. Lisp heuristics
    if sample.contains("(defun ") || sample.contains("(defmacro ") || (sample.contains("(let ") && sample.contains(";;;")) {
        return Some(TextSyntaxKind::LispSource);
    }

    // 14. Assembler heuristics
    let has_asm_section = sample.contains(".global ") || sample.contains(".globl ") || sample.contains(".section ");
    let has_asm_inst = sample.contains("mov ") || sample.contains("jmp ") || sample.contains("push ") || sample.contains("pop ");
    if has_asm_section && has_asm_inst {
        return Some(TextSyntaxKind::AssemblerSource);
    }

    None
}

/// Extracts interpreter details from a shebang line.
fn extract_shebang(data: &[u8]) -> Option<TextSyntaxKind> {
    let line_end = data.iter().position(|&b| b == b'\n' || b == b'\r').unwrap_or(data.len());
    let line_bytes = data.get(..line_end)?;
    let line_str = std::str::from_utf8(line_bytes).ok()?.trim_start_matches("#!").trim();
    if line_str.is_empty() {
        return None;
    }

    let mut parts = line_str.split_whitespace();
    let prog_path = parts.next()?;
    let prog_name = prog_path.rsplit(['/', '\\']).next().unwrap_or(prog_path);

    let (interp, _args) = if prog_name == "env" {
        // Handled format: #!/usr/bin/env <cmd> [args...]
        let cmd = parts.next().unwrap_or("env");
        (cmd, parts.collect::<Vec<_>>())
    } else {
        (prog_name, parts.collect::<Vec<_>>())
    };

    let interp_clean = interp.trim_start_matches(['-', '/']);
    let (fmt, mime, label) = match interp_clean {
        "sh" => (Some(FormatId::Sh), "text/x-shellscript".to_string(), "POSIX shell script".to_string()),
        "bash" => (Some(FormatId::Bash), "text/x-shellscript".to_string(), "Bourne-Again shell script".to_string()),
        "zsh" => (Some(FormatId::Sh), "text/x-shellscript".to_string(), "Zsh shell script".to_string()),
        "ksh" => (Some(FormatId::Sh), "text/x-shellscript".to_string(), "Korn shell script".to_string()),
        "csh" | "tcsh" => (Some(FormatId::Sh), "text/x-shellscript".to_string(), "C shell script".to_string()),
        "python" | "python3" | "python2" => (None, "text/x-python".to_string(), "Python script".to_string()),
        "perl" | "perl5" => (Some(FormatId::Perl), "text/x-perl".to_string(), "Perl script".to_string()),
        "ruby" => (None, "text/x-ruby".to_string(), "Ruby script".to_string()),
        "node" | "nodejs" => (Some(FormatId::JavaScript), "application/javascript".to_string(), "Node.js script".to_string()),
        "php" => (Some(FormatId::Php), "text/x-php".to_string(), "PHP script".to_string()),
        "awk" | "gawk" | "nawk" | "mawk" => (None, "text/x-awk".to_string(), "AWK script".to_string()),
        "sed" => (None, "text/x-sed".to_string(), "Sed script".to_string()),
        "lua" => (None, "text/x-lua".to_string(), "Lua script".to_string()),
        other => (None, "text/plain".to_string(), format!("{other} script")),
    };

    Some(TextSyntaxKind::ShebangScript {
        interpreter: interp.to_string(),
        format_id: fmt,
        mime,
        label,
    })
}

/// Formats the final description string with `file` parity.
#[must_use]
pub fn format_text_description(profile: &TextProfile) -> String {
    let mut desc = String::new();

    // 1. Syntax prefix or encoding name
    if let Some(syntax) = &profile.syntax {
        desc.push_str(syntax.description_prefix());
        desc.push_str(", ");
        desc.push_str(profile.encoding.description_label());
        desc.push_str(" text");
        if syntax.is_executable() {
            desc.push_str(" executable");
        }
    } else {
        desc.push_str(profile.encoding.description_label());
        desc.push_str(" text");
    }

    // 2. Very long lines clause
    if profile.has_long_lines {
        desc.push_str(&format!(", with very long lines ({})", profile.max_line_length));
    }

    // 3. Line terminators clause (only reported if not standard single LF, or if none)
    let n_total_lines = profile.n_crlf.saturating_add(profile.n_lf).saturating_add(profile.n_cr).saturating_add(profile.n_nel);
    if n_total_lines == 0 {
        desc.push_str(", with no line terminators");
    } else if profile.n_crlf > 0 || profile.n_cr > 0 || profile.n_nel > 0 {
        desc.push_str(", with ");
        let mut terms = Vec::new();
        if profile.n_crlf > 0 {
            terms.push("CRLF");
        }
        if profile.n_cr > 0 {
            terms.push("CR");
        }
        if profile.n_lf > 0 {
            terms.push("LF");
        }
        if profile.n_nel > 0 {
            terms.push("NEL");
        }
        desc.push_str(&terms.join(", "));
        desc.push_str(" line terminators");
    }

    // 4. Escapes and overstriking
    if profile.has_escapes {
        desc.push_str(", with escape sequences");
    }
    if profile.has_backspace {
        desc.push_str(", with overstriking");
    }

    desc
}

/// Performs complete text detection on a data source, returning a candidate if text is confirmed.
pub fn detect_text_candidate(
    source: &mut dyn DetectionSource,
    hint: Option<&DetectionHint>,
) -> Result<Option<DetectionCandidate>> {
    let mut sample_buf = vec![0u8; TEXT_ENCODING_MAX_BYTES.min(4096)];
    let n = source.read_at(0, &mut sample_buf)?;
    if n < 2 {
        return Ok(None);
    }
    // Reason for fallback: slice indexing within read count `n` is always valid
    let sample = sample_buf.get(..n).unwrap_or(&sample_buf);

    let Some(encoding) = detect_text_encoding(sample) else {
        return Ok(None);
    };

    let profile = profile_text_layout(sample, encoding);
    let description = format_text_description(&profile);

    // Determine candidate FormatId and MIME type
    let (format_id, mime) = if let Some(syntax) = &profile.syntax {
        (syntax.format_id().or_else(|| encoding.format_id()), Some(syntax.mime_type().to_string()))
    } else {
        (encoding.format_id(), Some(format!("text/plain; charset={}", encoding.mime_charset())))
    };

    // Calculate score
    let mut score = if profile.syntax.is_some() { 80u32 } else { 65u32 };
    let mut evidence = Vec::new();

    evidence.push(DetectionEvidence::Encoding {
        encoding: encoding.description_label().to_string(),
        score: 35,
    });

    evidence.push(DetectionEvidence::TextProperties {
        line_ending: profile.primary_line_ending,
        has_long_lines: profile.has_long_lines,
        has_escapes: profile.has_escapes,
        score: 30,
    });

    if let Some(syntax) = &profile.syntax {
        score = score.saturating_add(10);
        evidence.push(DetectionEvidence::Magic {
            description: syntax.description_prefix().to_string(),
            score: 10,
        });
    }

    // Concordance with hint extension
    if let Some(h) = hint {
        if let Some(ext) = h.extension.as_deref().or(h.filename.as_deref()) {
            let ext_lower = ext.to_ascii_lowercase();
            let is_match = match profile.syntax {
                Some(TextSyntaxKind::HtmlDocument) => ext_lower.ends_with(".html") || ext_lower.ends_with(".htm"),
                Some(TextSyntaxKind::XmlDocument) => ext_lower.ends_with(".xml"),
                Some(TextSyntaxKind::CSource) => ext_lower.ends_with(".c") || ext_lower.ends_with(".h"),
                Some(TextSyntaxKind::CppSource) => ext_lower.ends_with(".cpp") || ext_lower.ends_with(".cc") || ext_lower.ends_with(".cxx") || ext_lower.ends_with(".hpp"),
                Some(TextSyntaxKind::PythonScript) => ext_lower.ends_with(".py"),
                Some(TextSyntaxKind::ShellScript) => ext_lower.ends_with(".sh") || ext_lower.ends_with(".bash"),
                Some(TextSyntaxKind::PerlScript) => ext_lower.ends_with(".pl") || ext_lower.ends_with(".pm"),
                Some(TextSyntaxKind::RubySource) => ext_lower.ends_with(".rb"),
                _ => ext_lower.ends_with(".txt"),
            };
            if is_match {
                score = score.saturating_add(15);
                evidence.push(DetectionEvidence::Extension {
                    ext: ext.to_string(),
                    is_primary: true,
                    score: 15,
                });
            }
        }

        if let (Some(exp_cat), Some(fid)) = (h.expected_category, format_id) {
            if fid.category() == exp_cat {
                score = score.saturating_add(10);
                evidence.push(DetectionEvidence::CategoryMatch {
                    category: exp_cat,
                    score: 10,
                });
            }
        }
    }

    let confidence = if score >= 85 {
        ConfidenceTier::HighestConfidence
    } else if score >= 65 {
        ConfidenceTier::Strong
    } else {
        ConfidenceTier::Moderate
    };

    Ok(Some(DetectionCandidate {
        format_id,
        dc_id: None,
        mime,
        description,
        confidence,
        score,
        evidence,
    }))
}

