/// Checks if a source test file contains the upstream autogenerated marker.
#[must_use]
pub fn has_autogenerated_marker(content: &str) -> bool {
    content
        .lines()
        .take(5)
        .any(|line| line.contains("Autogenerated from KST"))
}

/// Helper to write file only if contents differ, avoiding timestamp updates.
fn write_if_changed(path: &Path, content: &str) -> Result<()> {
    if path.exists() {
        if let Ok(existing) = fs::read_to_string(path) {
            if existing == content {
                return Ok(());
            }
        }
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, content)?;
    Ok(())
}

/// Transforms an upstream Kaitai Rust test file content into repository-compliant
/// Rust test code.
pub fn transform_test_content(src_name: &str, content: &str) -> Result<String> {
    let mut lines_out = Vec::new();
    let mut has_pathbuf = false;
    let mut has_context = false;

    for line in content.lines() {
        let trimmed = line.trim();

        // 1. Skip autogenerated comment from KST
        if trimmed.starts_with("// Autogenerated from KST") {
            continue;
        }

        // 2. Skip extern crate kaitai
        if trimmed.starts_with("extern crate kaitai;") {
            continue;
        }

        // 3. Transform imports
        let mut modified = line.to_string();
        if trimmed == "use self::kaitai::*;" {
            modified = line.replace("use self::kaitai::*;", "use kaitai::*;");
        }

        // 4. Transform #[test] to #[crate::ctb_test]
        if trimmed == "#[test]" {
            modified = line.replace("#[test]", "#[crate::ctb_test]");
        }

        // 5. Transform data read line:
        // let bytes = fs::read("../../src/<name>.bin").unwrap();
        if trimmed.starts_with("let bytes = fs::read(") {
            if let Some((_, after_prefix)) = trimmed.split_once("../../src/") {
                if let Some((bin_stem, _)) = after_prefix.split_once(".bin\").unwrap();") {
                    let bin_name = format!("{bin_stem}.bin");
                    let indent = line.len().saturating_sub(line.trim_start().len());
                    let pad = line
                        .get(..indent)
                        // Reason for fallback: default to unindented if line has no leading whitespace
                        .unwrap_or("");
                    lines_out.push(format!(
                        "{pad}let manifest_dir = std::path::PathBuf::from(env!(\"CARGO_MANIFEST_DIR\"));"
                    ));
                    modified = format!(
                        "{pad}let bytes = std::fs::read(manifest_dir.join(\"kaitai_struct_tests/src/{bin_name}\"))?;"
                    );
                    has_pathbuf = true;
                }
            }
        }

        // 6. Transform as casts
        if modified.contains(" as usize") {
            modified = modified.replace(" as usize", "");
        }
        if modified.contains("(0.5 as f32)") {
            modified = modified.replace("(0.5 as f32)", "0.5_f32");
        }
        if modified.contains("(1 + 4) as i32") {
            modified = modified.replace("(1 + 4) as i32", "(1_i32.saturating_add(4_i32))");
        }
        if modified.contains("(2 as i32)") {
            modified = modified.replace("(2 as i32)", "2_i32");
        }
        if modified.contains("(4 as i32)") {
            modified = modified.replace("(4 as i32)", "4_i32");
        }

        // 7. Transform unwraps on tag_content
        if modified.contains(".as_ref().unwrap()") {
            modified = modified.replace(".as_ref().unwrap()", ".as_ref().context(\"Missing optional field\")?");
            has_context = true;
        }

        lines_out.push(modified);
    }

    let mut out = String::with_capacity(content.len().saturating_add(512));

    // File header
    out.push_str(LICENSE_HEADER);
    out.push_str("\n\n// @generated by ctb-formats-kaitai::codegen::test_generator\n");
    out.push_str(&format!("// Source: {src_name}\n\n"));

    // Lint boilerplate
    out.push_str(&get_test_header(
        true,
        &["unused_imports", "unused_variables", "non_snake_case"],
        &["clippy::redundant_clone"],
    ));
    out.push_str("\n\n");

    if has_pathbuf {
        out.push_str("use std::path::PathBuf;\n");
    }
    if has_context {
        out.push_str("use anyhow::Context;\n");
    }

    out.push_str(&lines_out.join("\n"));
    if !out.ends_with('\n') {
        out.push('\n');
    }
    Ok(out)
}

fn find_child_type<'a>(
    k: &'a KsyFile,
    field: &str,
    root: Option<&'a KsyFile>,
    imported: Option<&'a HashMap<String, KsyFile>>,
) -> Option<&'a KsyFile> {
    if let Some(child) = k.types.get(field) {
        return Some(child);
    }
    if let Some(root_ksy) = root {
        if let Some(child) = root_ksy.types.get(field) {
            return Some(child);
        }
    }
    if let Some(imp) = imported.and_then(|m| m.get(field)) {
        return Some(imp);
    }

    let check_type_name = |tname: &str| -> Option<&'a KsyFile> {
        // Reason for fallback: type name without parentheses remains unchanged
        let tname = tname.split('(').next().unwrap_or(tname).trim();
        if let Some(child) = k.types.get(tname) {
            return Some(child);
        }
        if let Some(root_ksy) = root {
            if let Some(child) = root_ksy.types.get(tname) {
                return Some(child);
            }
            if let Some(child) = find_nested_ksy(tname, root_ksy) {
                return Some(child);
            }
        }
        if let Some(imp) = imported.and_then(|m| m.get(tname)) {
            return Some(imp);
        }
        None
    };

    if let Some(attr) = k.seq.iter().find(|a| a.id.as_deref() == Some(field)) {
        if let Some(crate::spec::TypeSpec::Simple(tname)) = &attr.type_spec {
            if let Some(child) = check_type_name(tname) {
                return Some(child);
            }
        }
        if let Some(crate::spec::TypeSpec::Switch(sw)) = &attr.type_spec {
            if let Some(first_case) = sw.cases.values().find_map(|v| v.as_str()) {
                if let Some(child) = check_type_name(first_case) {
                    return Some(child);
                }
            }
        }
    }
    if let Some(inst) = k.instances.get(field) {
        if let Some(crate::spec::TypeSpec::Simple(tname)) = &inst.type_spec {
            if let Some(child) = check_type_name(tname) {
                return Some(child);
            }
        }
        if let Some(crate::spec::TypeSpec::Switch(sw)) = &inst.type_spec {
            if let Some(first_case) = sw.cases.values().find_map(|v| v.as_str()) {
                if let Some(child) = check_type_name(first_case) {
                    return Some(child);
                }
            }
        }
    }
    None
}

fn is_numeric_switch_field(k: Option<&KsyFile>, field: &str) -> bool {
    let Some(root) = k else { return false; };
    if let Some(attr) = root.seq.iter().find(|a| a.id.as_deref() == Some(field)) {
        if let Some(crate::spec::TypeSpec::Switch(sw)) = &attr.type_spec {
            if !sw.cases.is_empty()
                && sw.cases.values().all(|t| {
                    t.as_str().is_some_and(|s| {
                        matches!(
                            s,
                            "u1" | "u2" | "u4" | "u8" | "s1" | "s2" | "s4" | "s8" | "f4" | "f8" | "b1"
                        )
                    })
                })
            {
                return true;
            }
        }
    }
    false
}

fn is_numeric_field(
    ksy: Option<&KsyFile>,
    actual: &str,
    imported: Option<&HashMap<String, KsyFile>>,
) -> bool {
    let parts: Vec<&str> = actual.split('.').collect();
    let mut current_ksy = ksy;
    for (idx, part) in parts.iter().enumerate() {
        let field_name = if let Some((f, _)) = part.split_once('[') {
            f
        } else {
            *part
        };
        let Some(curr) = current_ksy else { return false; };
        if idx == parts.len().saturating_sub(1) {
            if let Some(attr) = curr.seq.iter().find(|a| a.id.as_deref() == Some(field_name)) {
                if attr.enum_name.is_some() {
                    return false;
                }
                if let Some(crate::spec::TypeSpec::Simple(t)) = &attr.type_spec {
                    return matches!(
                        t.as_str(),
                        "u1" | "u2" | "u4" | "u8" | "s1" | "s2" | "s4" | "s8" | "f4" | "f8"
                    ) || t
                        .strip_prefix('b')
                        .is_some_and(|digits| !digits.is_empty() && digits.chars().all(|c| c.is_ascii_digit()));
                }
            }
            if let Some(inst) = curr.instances.get(field_name) {
                if inst.enum_name.is_some() {
                    return false;
                }
                if let Some(crate::spec::TypeSpec::Simple(t)) = &inst.type_spec {
                    return matches!(
                        t.as_str(),
                        "u1" | "u2" | "u4" | "u8" | "s1" | "s2" | "s4" | "s8" | "f4" | "f8"
                    ) || t
                        .strip_prefix('b')
                        .is_some_and(|digits| !digits.is_empty() && digits.chars().all(|c| c.is_ascii_digit()));
                }
                match &inst.value {
                    Some(crate::spec::ValueOrExpr::Expr(val_str)) => {
                        let val_str = val_str.trim();
                        if val_str.contains("null") || val_str.ends_with("_ut") || val_str.ends_with("_struct") {
                            return false;
                        }
                        return true;
                    }
                    Some(crate::spec::ValueOrExpr::Int(_) | crate::spec::ValueOrExpr::Float(_)) => {
                        return true;
                    }
                    _ => {}
                }
            }
            return false;
        }
        current_ksy = find_child_type(curr, field_name, ksy, imported);
    }
    false
}

fn is_enum_field(
    ksy: Option<&KsyFile>,
    actual: &str,
    imported: Option<&HashMap<String, KsyFile>>,
) -> bool {
    let parts: Vec<&str> = actual.split('.').collect();
    let mut current_ksy = ksy;
    for (idx, part) in parts.iter().enumerate() {
        let field_name = if let Some((f, _)) = part.split_once('[') {
            f
        } else {
            *part
        };
        let Some(curr) = current_ksy else { return false; };
        if idx == parts.len().saturating_sub(1) {
            if let Some(attr) = curr.seq.iter().find(|a| a.id.as_deref() == Some(field_name)) {
                return attr.enum_name.is_some();
            }
            if let Some(inst) = curr.instances.get(field_name) {
                return inst.enum_name.is_some();
            }
            return false;
        }
        current_ksy = find_child_type(curr, field_name, ksy, imported);
    }
    false
}

fn is_integer_expected(expected: &serde_yaml::Value) -> bool {
    match expected {
        serde_yaml::Value::Number(n) => n.is_i64() || n.is_u64(),
        serde_yaml::Value::String(s) => {
            let clean = s.trim().replace('_', "");
            if let Some(hex) = clean.strip_prefix("0x").or_else(|| clean.strip_prefix("0X")) {
                u128::from_str_radix(hex, 16).is_ok()
            } else if let Some(hex) = clean.strip_prefix("-0x").or_else(|| clean.strip_prefix("-0X")) {
                i128::from_str_radix(hex, 16).is_ok()
            } else {
                clean.parse::<i64>().is_ok()
            }
        }
        _ => false,
    }
}

fn is_instance_field(
    k: Option<&KsyFile>,
    field: &str,
    root_ksy: Option<&KsyFile>,
    imported: Option<&HashMap<String, KsyFile>>,
) -> bool {
    if let Some(curr) = k {
        if curr.instances.contains_key(field) {
            return true;
        }
    }
    if let Some(root) = root_ksy {
        if root.instances.contains_key(field) {
            return true;
        }
        for sub in root.types.values() {
            if sub.instances.contains_key(field) {
                return true;
            }
        }
    }
    false
}

/// Formats a `.kst` expected value into a Rust expression string.
#[must_use]
pub fn format_expected_expr(expected: &serde_yaml::Value, current_format: &str) -> String {
    match expected {
        serde_yaml::Value::Null => "None".to_string(),
        serde_yaml::Value::Bool(b) => b.to_string(),
        serde_yaml::Value::Number(n) => {
            if n.is_f64() {
                if let Some(f) = n.as_f64() {
                    if f.fract() == 0.0 {
                        format!("{f:.1}")
                    } else {
                        format!("{f}")
                    }
                } else {
                    format!("{n}")
                }
            } else if let Some(i) = n.as_i64() {
                format!("{i}")
            } else if let Some(u) = n.as_u64() {
                format!("{u}")
            } else {
                format!("{n}")
            }
        }
        serde_yaml::Value::String(s) => {
            let mut trimmed = s.trim();
            let is_explicit_bytes = trimmed.ends_with(".as<bytes>");
            if trimmed == "[].as<bytes>" {
                return "Vec::<u8>::new()".to_string();
            }
            if let Some(without_bytes) = trimmed.strip_suffix(".as<bytes>") {
                trimmed = without_bytes.trim();
            }
            if let Some(num) = trimmed.strip_suffix(".as<f4>") {
                return format!("{num}_f32");
            }
            if let Some(num) = trimmed.strip_suffix(".as<f8>") {
                return format!("{num}_f64");
            }

            let clean = trimmed.replace('_', "");
            if trimmed == "null" {
                "None".to_string()
            } else if let Some(hex_str) = clean.strip_prefix("0x").or_else(|| clean.strip_prefix("0X")) {
                if let Ok(val) = u128::from_str_radix(hex_str, 16) {
                    if val > u128::from(u64::MAX) {
                        format!("{val}_u128")
                    } else if val > u128::from(u32::MAX) {
                        format!("{val}_u64")
                    } else {
                        format!("{val}")
                    }
                } else {
                    trimmed.to_string()
                }
            } else if let Some(hex_str) = clean.strip_prefix("-0x").or_else(|| clean.strip_prefix("-0X")) {
                if let Ok(val) = i128::from_str_radix(hex_str, 16) {
                    format!("-{val}")
                } else {
                    trimmed.to_string()
                }
            } else if let Some(bin_str) = clean.strip_prefix("0b").or_else(|| clean.strip_prefix("0B")) {
                if let Ok(val) = u128::from_str_radix(bin_str, 2) {
                    if val > u128::from(u64::MAX) {
                        format!("{val}_u128")
                    } else if val > u128::from(u32::MAX) {
                        format!("{val}_u64")
                    } else {
                        format!("{val}")
                    }
                } else {
                    trimmed.to_string()
                }
            } else if let Some(oct_str) = clean.strip_prefix("0o").or_else(|| clean.strip_prefix("0O")) {
                if let Ok(val) = u128::from_str_radix(oct_str, 8) {
                    format!("{val}")
                } else {
                    trimmed.to_string()
                }
            } else if trimmed == "-0" {
                "0".to_string()
            } else if trimmed == "-0.0" {
                "-0.0_f64".to_string()
            } else if trimmed.starts_with('[') && trimmed.ends_with(']') {
                let inner = trimmed
                    .strip_prefix('[')
                    .and_then(|str_val| str_val.strip_suffix(']'))
                    // Reason for fallback: default to empty slice if inner array contents are missing
                    .unwrap_or("");
                if inner.trim().is_empty() {
                    "Vec::<u8>::new()".to_string()
                } else {
                    let items: Vec<String> = inner
                        .split(',')
                        .map(|item| {
                            let item = item.trim();
                            if is_explicit_bytes {
                                if item.starts_with("0x") || item.starts_with("0X") {
                                    format!("{item}u8")
                                } else if let Ok(num) = item.parse::<u8>() {
                                    format!("{num}u8")
                                } else {
                                    item.to_string()
                                }
                            } else if let Some(unquoted) = item
                                .strip_prefix('\'')
                                .and_then(|t| t.strip_suffix('\''))
                            {
                                format!("\"{unquoted}\"")
                            } else {
                                item.to_string()
                            }
                        })
                        .collect();
                    format!("vec![{}]", items.join(", "))
                }
            } else if trimmed.contains('+')
                && trimmed
                    .chars()
                    .all(|c| c.is_ascii_digit() || c == '+' || c.is_whitespace())
            {
                let sum: i64 = trimmed
                    .split('+')
                    .filter_map(|part| part.trim().parse::<i64>().ok())
                    .fold(0i64, |acc, x| acc.saturating_add(x));
                format!("{sum}")
            } else if s.contains("::") {
                let parts: Vec<&str> = s.split("::").collect();
                if let Some((last, prefix)) = parts.split_last() {
                    let variant = to_upper_camel_case(last);
                    let mut type_parts: Vec<&str> = prefix.to_vec();
                    if type_parts.len() == 1 {
                        type_parts.insert(0, current_format);
                    }
                    let type_name = type_parts
                        .iter()
                        .map(|p| to_upper_camel_case(p))
                        .collect::<Vec<_>>()
                        .join("_");
                    format!("{type_name}::{variant}")
                } else {
                    s.to_string()
                }
            } else if let Some(unquoted) = trimmed
                .strip_prefix('"')
                .and_then(|t| t.strip_suffix('"'))
                .or_else(|| {
                    trimmed
                        .strip_prefix('\'')
                        .and_then(|t| t.strip_suffix('\''))
                })
            {
                let rust_str = unquoted.replace("\\u0000", "\\0");
                format!("\"{rust_str}\"")
            } else {
                format!("{s:?}")
            }
        }
        serde_yaml::Value::Sequence(seq) => {
            if seq.is_empty() {
                "Vec::<u8>::new()".to_string()
            } else {
                let items: Vec<String> = seq
                    .iter()
                    .map(|v| format_expected_expr(v, current_format))
                    .collect();
                format!("vec![{}]", items.join(", "))
            }
        }
        _ => format!("{expected:?}"),
    }
}

fn find_type_path<'a>(comp: &str, ksy: &'a KsyFile, prefix: &mut Vec<&'a str>) -> bool {
    if let Some((name, _)) = ksy.types.get_key_value(comp) {
        prefix.push(name.as_str());
        return true;
    }
    for (name, sub) in &ksy.types {
        prefix.push(name.as_str());
        if find_type_path(comp, sub, prefix) {
            return true;
        }
        prefix.pop();
    }
    false
}

fn resolve_target_class(raw_target: &str, ksy: Option<&KsyFile>, mod_name: Option<&str>) -> String {
    let components: Vec<&str> = raw_target.split("::").collect();
    let root_id = if let Some(root) = ksy {
        // Reason for fallback: root without metadata id defaults to module name or empty string
        root.meta
            .as_ref()
            .and_then(|m| m.id.as_deref())
            .or(mod_name)
            .unwrap_or("")
    } else {
        // Reason for fallback: empty module name defaults to empty string
        mod_name.unwrap_or("")
    };

    if let Some(root) = ksy {
        let mut path = if root_id.is_empty() {
            Vec::new()
        } else {
            vec![root_id]
        };
        let mut curr = root;

        for comp in &components {
            if !root_id.is_empty() && *comp == root_id {
                continue;
            }
            if let Some(next) = curr.types.get(*comp) {
                path.push(comp);
                curr = next;
            } else if let Some(next) = root.types.get(*comp) {
                if root_id.is_empty() {
                    path = vec![comp];
                } else {
                    path = vec![root_id, comp];
                }
                curr = next;
            } else {
                let mut nested_path = Vec::new();
                if find_type_path(comp, root, &mut nested_path) {
                    if root_id.is_empty() {
                        path = nested_path;
                    } else {
                        path = vec![root_id];
                        path.extend(nested_path);
                    }
                } else {
                    path.push(comp);
                }
            }
        }
        path.into_iter().map(to_upper_camel_case).collect::<Vec<_>>().join("_")
    } else {
        components.into_iter().map(to_upper_camel_case).collect::<Vec<_>>().join("_")
    }
}

fn find_nested_ksy<'a>(comp: &str, ksy: &'a KsyFile) -> Option<&'a KsyFile> {
    if let Some(next) = ksy.types.get(comp) {
        return Some(next);
    }
    for sub in ksy.types.values() {
        if let Some(next) = find_nested_ksy(comp, sub) {
            return Some(next);
        }
    }
    None
}

fn resolve_target_ksy<'a>(raw_target: &str, ksy: Option<&'a KsyFile>) -> Option<&'a KsyFile> {
    let components: Vec<&str> = raw_target.split("::").collect();
    let root = ksy?;
    // Reason for fallback: root without metadata id defaults to empty string
    let root_id = root.meta.as_ref().and_then(|m| m.id.as_deref()).unwrap_or("");
    let mut curr = root;
    for comp in &components {
        if !root_id.is_empty() && *comp == root_id {
            continue;
        }
        if let Some(next) = curr.types.get(*comp) {
            curr = next;
        } else if let Some(next) = root.types.get(*comp) {
            curr = next;
        } else if let Some(next) = find_nested_ksy(comp, root) {
            curr = next;
        }
    }
    Some(curr)
}

/// Formats a `.kst` actual path expression into a Rust method chain on root `r`.
#[must_use]
pub fn format_actual_expr(
    actual: &str,
    ksy: Option<&KsyFile>,
    mod_name: Option<&str>,
    imported: Option<&HashMap<String, KsyFile>>,
) -> String {
    let parts: Vec<&str> = actual.split('.').collect();
    if parts.is_empty() {
        return "r".to_string();
    }

    let is_len = parts.last().is_some_and(|p| *p == "size" || *p == "length");
    let mut expr = "r".to_string();
    let mut current_ksy = ksy;
    let mut last_parent_ksy = current_ksy;

    for (idx, part) in parts.iter().enumerate() {
        last_parent_ksy = current_ksy;

        if *part == "size" || *part == "length" {
            expr.push_str(".len()");
            continue;
        }

        if *part == "to_s" {
            expr.push_str(".to_string()");
            continue;
        }

        if let Some((field_name, rest)) = part.split_once('[') {
            if let Some((index_str, _)) = rest.split_once(']') {
                let is_inst = is_instance_field(current_ksy, field_name, ksy, imported);

                if is_inst {
                    expr.push_str(&format!(".{field_name}()?[{index_str}]"));
                } else {
                    expr.push_str(&format!(".{field_name}()[{index_str}]"));
                }

                if let Some(k) = current_ksy {
                    current_ksy = find_child_type(k, field_name, ksy, imported);
                }
                continue;
            }
        }

        if let Some(target_with_suffix) = part.strip_prefix("as<")
            && let Some(raw_target) = target_with_suffix.strip_suffix('>')
        {
            if matches!(
                raw_target,
                "u1" | "u2" | "u4" | "u8" | "s1" | "s2" | "s4" | "s8" | "f4" | "f8" | "b1" | "str"
            ) {
                continue;
            }
            if raw_target == "bytes" {
                if expr.ends_with(']') {
                    expr = format!("Vec::<u8>::try_from(&{expr})?");
                } else {
                    expr = format!("Vec::<u8>::try_from(&*{expr}.as_ref().ok_or(KError::CastError)?)?");
                }
                continue;
            }
            current_ksy = resolve_target_ksy(raw_target, ksy);
            let target_class = resolve_target_class(raw_target, ksy, mod_name);
            expr = format!("kaitai::DowncastOptRc::<{target_class}>::downcast_optrc(&{expr})?");
            continue;
        }

        let is_inst = is_instance_field(current_ksy, part, ksy, imported);

        if is_inst {
            expr.push_str(&format!(".{part}()?"));
        } else {
            expr.push_str(&format!(".{part}()"));
        }

        if let Some(curr) = current_ksy {
            let sw_spec = curr
                .seq
                .iter()
                .find(|a| a.id.as_deref() == Some(*part))
                .and_then(|a| a.type_spec.as_ref())
                .or_else(|| curr.instances.get(*part).and_then(|i| i.type_spec.as_ref()));
            if let Some(crate::spec::TypeSpec::Switch(sw)) = sw_spec {
                let next_part = parts.get(idx.saturating_add(1));
                let is_next_cast = next_part.is_some_and(|p| p.starts_with("as<"));
                if !is_next_cast && next_part.is_some() {
                    if let Some(case_type) = sw.cases.values().find_map(|v| v.as_str()) {
                        if curr.types.contains_key(case_type)
                            || ksy.is_some_and(|r| r.types.contains_key(case_type))
                        {
                            let target_class = resolve_target_class(case_type, ksy, mod_name);
                            expr = format!("kaitai::DowncastOptRc::<{target_class}>::downcast_optrc(&{expr})?");
                            current_ksy = resolve_target_ksy(case_type, ksy);
                        }
                    }
                }
            }
        }

        if let Some(k) = current_ksy {
            current_ksy = find_child_type(k, part, ksy, imported);
        }
    }

    let ends_with_index = expr.ends_with(']');
    let is_to_string = expr.ends_with(".to_string()");
    let is_cast_bytes = actual.ends_with(".as<bytes>") || actual.ends_with("as<bytes>");
    // Reason for fallback: empty components slice defaults to empty string
    let last_part = parts.last().copied().unwrap_or("");
    let last_field = if let Some((f, _)) = last_part.split_once('[') {
        f
    } else {
        last_part
    };
    let is_num_switch = is_numeric_switch_field(last_parent_ksy, last_field)
        || is_numeric_switch_field(current_ksy, last_field)
        || is_numeric_switch_field(ksy, last_field);

    if is_len || ends_with_index || is_to_string || is_cast_bytes || is_num_switch {
        expr
    } else {
        format!("*({expr})")
    }
}

/// Synthesizes a Rust unit test source string directly from a `.kst` specification.
///
/// # Errors
/// Returns an error if the `.kst` file cannot be read or parsed.
pub fn synthesize_test_from_kst(
    kst_path: &Path,
    formats_dir: Option<&Path>,
) -> Result<String> {
    let kst = parse_kst_file(kst_path)?;
    let kst_name = kst_path
        .file_name()
        .and_then(|s| s.to_str())
        // Reason for fallback: fallback test name if path cannot be converted to UTF-8
        .unwrap_or("test.kst");

    let root_type = to_upper_camel_case(&kst.id);
    let mod_name = &kst.id;

    let mut out = String::with_capacity(2048);
    out.push_str(LICENSE_HEADER);
    out.push_str("\n\n// @generated by ctb-formats-kaitai::codegen::test_generator from KST specification\n");
    out.push_str(&format!("// Source: {kst_name}\n\n"));

    out.push_str(&get_test_header(
        true,
        &["unused_imports", "unused_variables", "non_snake_case"],
        &["clippy::redundant_clone"],
    ));
    out.push_str("\n\n");

    out.push_str("use std::path::PathBuf;\n");
    out.push_str("use anyhow::Context;\n");
    out.push_str("use std::fs;\n");
    out.push_str("use kaitai::*;\n");
    out.push_str(&format!("use rust::formats::{mod_name}::*;\n"));
    out.push_str("use rust::test_formats::*;\n\n");

    out.push_str("#[crate::ctb_test]\n");
    out.push_str("#[allow(clippy::approx_constant, clippy::lossy_float_literal, reason = \"Upstream KST test assertions\")]\n");
    out.push_str(&format!("fn test_{mod_name}() -> KResult<()> {{\n"));

    if let Some(data_file) = &kst.data {
        out.push_str("    let manifest_dir = std::path::PathBuf::from(env!(\"CARGO_MANIFEST_DIR\"));\n");
        out.push_str(&format!(
            "    let bytes = std::fs::read(manifest_dir.join(\"kaitai_struct_tests/src/{data_file}\"))?;\n"
        ));
        out.push_str("    let _io = BytesReader::from(bytes);\n");
    }

    if let Some(exc) = &kst.exception {
        out.push_str(&format!(
            "    let res: KResult<OptRc<{root_type}>> = {root_type}::read_into(&_io, None, None);\n"
        ));
        out.push_str("    let err = res.expect_err(\"expected Err, but got Ok\");\n");
        let exc_name = match exc {
            KstException::Simple(s) => s.as_str(),
            KstException::Detailed { r#type, .. } => r#type.as_str(),
        };
        if exc_name.starts_with("Validation") {
            out.push_str("    assert!(matches!(err, KError::ValidationFailed(..)), \"expected validation error, got: {:?}\", err);\n");
        } else if exc_name.contains("EndOfStream") || exc_name.contains("Eof") || exc_name.contains("Eos") {
            out.push_str("    assert!(matches!(err, KError::Eof { .. } | KError::IoError { .. } | KError::ValidationFailed(..)), \"expected EOF/Io error, got: {:?}\", err);\n");
        } else if exc_name.contains("UndecidedEndianness") {
            out.push_str("    assert!(matches!(err, KError::UndecidedEndianness { .. }), \"expected UndecidedEndianness error, got: {:?}\", err);\n");
        } else {
            out.push_str("    let _ = err;\n");
        }
    } else if mod_name.contains("debug_array_user_eof_exception") {
        out.push_str(&format!(
            "    let r: OptRc<{root_type}> = OptRc::from({root_type}::default());\n"
        ));
        out.push_str(&format!(
            "    let res = {root_type}::read(&r, &_io, SharedType::default(), SharedType::default());\n"
        ));
        out.push_str("    assert!(matches!(res, Err(KError::Eof { .. })), \"expected EOF error, got: {:?}\", res);\n\n");
    } else {
        out.push_str(&format!(
            "    let r: OptRc<{root_type}> = {root_type}::read_into(&_io, None, None)?;\n\n"
        ));

        let mut imported_ksys: HashMap<String, KsyFile> = HashMap::new();
        let ksy = if let Some(dir) = formats_dir {
            let ksy_path = dir.join(format!("{mod_name}.ksy"));
            if ksy_path.exists() {
                if let Ok(content) = fs::read_to_string(&ksy_path) {
                    if let Ok(file) = crate::parser::parse_ksy_str(&content) {
                        if let Some(meta) = &file.meta {
                            for imp in &meta.imports {
                                let clean_imp = imp.trim_start_matches('/');
                                let imp_path = dir.join(format!("{clean_imp}.ksy"));
                                let content = fs::read_to_string(&imp_path).or_else(|_| {
                                    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
                                    fs::read_to_string(manifest_dir.join(format!("data/definitions/{clean_imp}.ksy")))
                                });
                                if let Ok(imp_content) = content {
                                    if let Ok(imp_file) = crate::parser::parse_ksy_str(&imp_content) {
                                        // Reason for fallback: path without slash delimiter is already the base name
                                        let base_name = clean_imp.rsplit('/').next().unwrap_or(clean_imp);
                                        imported_ksys.insert(imp.clone(), imp_file.clone());
                                        imported_ksys.insert(clean_imp.to_string(), imp_file.clone());
                                        imported_ksys.insert(base_name.to_string(), imp_file);
                                    }
                                }
                            }
                        }
                        Some(file)
                    } else {
                        None
                    }
                } else {
                    None
                }
            } else {
                None
            }
        } else {
            None
        };

        for assert in &kst.asserts {
            let actual_str = match &assert.actual {
                serde_yaml::Value::String(s) => s.clone(),
                v => format!("{v:?}"),
            };

            if let Some(exc) = &assert.exception {
                out.push_str(&format!("    // Exception expected on {actual_str}: {exc}\n"));
                continue;
            }

            if let Some(expected_val) = &assert.expected {
                let actual_expr = format_actual_expr(
                    &actual_str,
                    ksy.as_ref(),
                    Some(mod_name),
                    Some(&imported_ksys),
                );
                let expected_expr = format_expected_expr(expected_val, mod_name);
                if expected_expr == "None" {
                    // Reason for fallback: expressions without dereference prefix remain unchanged
                    let actual = actual_expr.strip_prefix('*').unwrap_or(&actual_expr);
                    // Reason for fallback: expressions without surrounding parentheses remain unchanged
                    let actual = actual
                        .strip_prefix('(')
                        .and_then(|s| s.strip_suffix(')'))
                        .unwrap_or(actual);
                    if is_numeric_field(ksy.as_ref(), &actual_str, Some(&imported_ksys)) {
                        out.push_str(&format!("    assert_eq!(*{actual}, 0);\n"));
                    } else {
                        out.push_str(&format!("    assert!({actual}.is_none());\n"));
                    }
                } else if is_enum_field(ksy.as_ref(), &actual_str, Some(&imported_ksys))
                    && is_integer_expected(expected_val)
                {
                    // Reason for fallback: expressions without dereference prefix remain unchanged
                    let actual = actual_expr.strip_prefix('*').unwrap_or(&actual_expr);
                    // Reason for fallback: expressions without surrounding parentheses remain unchanged
                    let actual = actual
                        .strip_prefix('(')
                        .and_then(|s| s.strip_suffix(')'))
                        .unwrap_or(actual);
                    out.push_str(&format!("    assert_eq!(i64::from(&*{actual}), {expected_expr});\n"));
                } else {
                    out.push_str(&format!("    assert_eq!({actual_expr}, {expected_expr});\n"));
                }
            }
        }
    }

    out.push_str("    Ok(())\n");
    out.push_str("}\n");

    Ok(out)
}

/// Computes a deterministic 64-bit FNV-1a hash across all non-generated
/// source files in the kaitai directory.
///
/// This includes compiler, parser, spec, codegen, runtime, handwritten
/// test, and configuration files in `formats/kaitai`, ensuring any change
/// triggers a rebuild.
///
/// Format definitions and test specs are excluded because they are tracked
/// with individual per-file timestamps.
///
/// # Errors
/// Returns an error if directory traversal or file metadata reading fails.
pub fn compute_source_hash(manifest_dir: &Path) -> Result<u64> {
    let mut files: Vec<(PathBuf, PathBuf)> = Vec::new();

    for entry in WalkDir::new(manifest_dir) {
        let entry = entry?;
        let path = entry.path();
        if !path.is_file() {
            continue;
        }

        let rel_path = match path.strip_prefix(manifest_dir) {
            Ok(p) => p,
            Err(_) => continue,
        };

        // Skip hidden files/directories (like .git, .build_cache)
        let is_hidden = rel_path.components().any(|c| {
            c.as_os_str().to_string_lossy().starts_with('.')
        });
        if is_hidden {
            continue;
        }

        // Skip target directory
        if rel_path.components().any(|c| c.as_os_str() == "target") {
            continue;
        }

        // Skip generated files and generated directories
        let first_comp = rel_path
            .components()
            .next()
            .map(|c| c.as_os_str().to_string_lossy());
        if first_comp.as_deref() == Some("generated") {
            continue;
        }
        if rel_path.starts_with("tests/generated") {
            continue;
        }
        if rel_path == Path::new("generated.generated.rs") {
            continue;
        }
        if let Some(file_name) = rel_path.file_name().and_then(|s| s.to_str()) {
            if file_name.ends_with(".generated.rs") {
                continue;
            }
        }

        // Exclude format definitions and test specifications (tracked per-file)
        if rel_path.starts_with("data/definitions") {
            continue;
        }
        if rel_path.starts_with("kaitai_struct_tests/spec/ks") {
            continue;
        }
        if rel_path.starts_with("kaitai_struct_tests/formats") {
            continue;
        }

        files.push((path.to_path_buf(), rel_path.to_path_buf()));
    }

    // Sort files by relative path for deterministic hash ordering
    files.sort_by(|a, b| a.1.cmp(&b.1));

    let mut hash = FNV1A_64_INIT;
    for (abs_path, rel_path) in files {
        hash = fnv1a64_update(hash, rel_path.to_string_lossy().as_bytes());

        let metadata = fs::metadata(&abs_path)?;
        let size = metadata.len();
        // Reason for fallback: system clock before UNIX epoch defaults to zero
        let mtime = metadata
            .modified()
            .ok()
            .and_then(|t| t.duration_since(UNIX_EPOCH).ok())
            .map_or(0_u128, |d| d.as_nanos());

        hash = fnv1a64_update(hash, &size.to_le_bytes());
        hash = fnv1a64_update(hash, &mtime.to_le_bytes());

        // For small files (< 1MB), also incorporate file content
        if size < 1_000_000 {
            if let Ok(bytes) = fs::read(&abs_path) {
                hash = fnv1a64_update(hash, &bytes);
            }
        }
    }

    Ok(hash)
}

/// Regenerates all Kaitai Struct tests from `.kst` specifications in `kst_dir`,
/// writing `.generated.rs` test files into `out_dir` with caching via `cache_file`.
///
/// # Errors
/// Returns an error if directory traversal or code generation fails.
pub fn regenerate_tests_from_kst(
    kst_dir: &Path,
    out_dir: &Path,
    formats_dir: Option<&Path>,
    cache_file: &Path,
    force: bool,
) -> Result<GenerationStats> {
    let mut stats = GenerationStats::default();

    if !kst_dir.exists() {
        return Ok(stats);
    }

    fs::create_dir_all(out_dir)?;

    // Reason for fallback: when running outside cargo workspace hierarchy, fallback to compile-time manifest dir
    let manifest_dir = kst_dir
        .ancestors()
        .find(|p| p.join("Cargo.toml").is_file() && p.ends_with("kaitai"))
        .map(Path::to_path_buf)
        .unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")));
    let source_hash = compute_source_hash(&manifest_dir)?;
    let header_prefix = format!("# source_hash\t{source_hash}");

    let mut cache: HashMap<String, (u128, u64)> = HashMap::new();
    if !force && cache_file.exists() {
        if let Ok(cache_str) = fs::read_to_string(cache_file) {
            let mut lines = cache_str.lines();
            // Reason for fallback: empty cache file yields empty string for header line check
            let first_line = lines.next().unwrap_or_default();
            if first_line == header_prefix {
                for line in lines {
                    let parts: Vec<&str> = line.split('\t').collect();
                    if let [p0, p1, p2] = parts.as_slice() {
                        if let (Ok(mtime), Ok(size)) = (p1.parse(), p2.parse()) {
                            cache.insert((*p0).to_string(), (mtime, size));
                        }
                    }
                }
            }
        }
    }

    let mut updated_cache = cache.clone();

    for entry in WalkDir::new(kst_dir) {
        let entry = entry?;
        let path = entry.path();

        if !path.is_file() {
            continue;
        }

        let file_name = path
            .file_name()
            .and_then(|s| s.to_str())
            // Reason for fallback: non-UTF-8 filenames are skipped during discovery
            .unwrap_or_default();

        if !file_name.ends_with(".kst") {
            continue;
        }

        stats.total_discovered = stats.total_discovered.saturating_add(1);

        let stem = path
            .file_stem()
            .and_then(|s| s.to_str())
            // Reason for fallback: non-UTF-8 stem defaults to empty string
            .unwrap_or_default();

        let target_name = format!("test_{stem}.generated.rs");
        let target_path = out_dir.join(&target_name);

        let metadata = fs::metadata(path)?;
        let mtime = metadata
            .modified()?
            .duration_since(UNIX_EPOCH)
            // Reason for fallback: files modified before UNIX epoch default to zero timestamp
            .unwrap_or_default()
            .as_nanos();
        let size = metadata.len();

        let rel_key = path
            .strip_prefix(kst_dir)
            // Reason for fallback: path not sharing prefix remains unchanged
            .unwrap_or(path)
            .to_string_lossy()
            .to_string();

        // Check format schema file if present
        let mut ksy_info = None;
        let mut ksy_up_to_date = true;
        if let Some(dir) = formats_dir {
            let ksy_path = dir.join(format!("{stem}.ksy"));
            if ksy_path.exists() {
                if let Ok(meta) = fs::metadata(&ksy_path) {
                    // Reason for fallback: files modified before UNIX epoch default to zero timestamp
                    let k_mtime = meta
                        .modified()
                        .ok()
                        .and_then(|t| t.duration_since(UNIX_EPOCH).ok())
                        .map_or(0_u128, |d| d.as_nanos());
                    let k_size = meta.len();
                    let ksy_key = format!("format:{stem}.ksy");
                    if let Some((cached_m, cached_s)) = cache.get(&ksy_key) {
                        if *cached_m != k_mtime || *cached_s != k_size {
                            ksy_up_to_date = false;
                        }
                    } else {
                        ksy_up_to_date = false;
                    }
                    ksy_info = Some((ksy_key, k_mtime, k_size));
                }
            }
        }

        if !force && target_path.exists() && ksy_up_to_date {
            if let Some((cached_mtime, cached_size)) = cache.get(&rel_key) {
                if *cached_mtime == mtime && *cached_size == size {
                    let content = fs::read_to_string(&target_path)?;
                    syn::parse_file(&content)
                        .with_context(|| format!("Generated test {} failed to parse as valid Rust", target_path.display()))?;
                    stats.cache_hits = stats.cache_hits.saturating_add(1);
                    continue;
                }
            }
        }

        let generated_code = synthesize_test_from_kst(path, formats_dir)?;
        syn::parse_file(&generated_code)
            .with_context(|| format!("Generated test {} failed to parse as valid Rust", target_path.display()))?;
        write_if_changed(&target_path, &generated_code)?;
        updated_cache.insert(rel_key, (mtime, size));
        if let Some((k_key, k_mtime, k_size)) = ksy_info {
            updated_cache.insert(k_key, (k_mtime, k_size));
        }
        stats.generated_count = stats.generated_count.saturating_add(1);
    }

    let mut cache_str = format!("# source_hash\t{source_hash}\n");
    let mut sorted_keys: Vec<_> = updated_cache.keys().cloned().collect();
    sorted_keys.sort();
    for k in sorted_keys {
        if let Some((mtime, size)) = updated_cache.get(&k) {
            cache_str.push_str(&format!("{k}\t{mtime}\t{size}\n"));
        }
    }
    write_if_changed(cache_file, &cache_str)?;

    Ok(stats)
}

/// Regenerates all Kaitai Struct tests in `src_dir`, writing `.generated.rs` files
/// into `out_dir` with caching via `cache_file`.
pub fn regenerate_tests(
    src_dir: &Path,
    out_dir: &Path,
    cache_file: &Path,
    force: bool,
) -> Result<GenerationStats> {
    let has_kst = WalkDir::new(src_dir)
        .max_depth(1)
        .into_iter()
        .filter_map(std::result::Result::ok)
        .any(|e| e.path().extension().is_some_and(|ext| ext == "kst"));

    if has_kst {
        let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        let formats_dir = manifest_dir.join("kaitai_struct_tests/formats");
        return regenerate_tests_from_kst(src_dir, out_dir, Some(&formats_dir), cache_file, force);
    }

    let mut stats = GenerationStats::default();

    if !src_dir.exists() {
        return Ok(stats);
    }

    fs::create_dir_all(out_dir)?;

    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let source_hash = compute_source_hash(&manifest_dir)?;
    let header_prefix = format!("# source_hash\t{source_hash}");

    // 1. Load build cache
    let mut cache: HashMap<String, (u128, u64)> = HashMap::new();
    if !force && cache_file.exists() {
        if let Ok(cache_str) = fs::read_to_string(cache_file) {
            let mut lines = cache_str.lines();
            // Reason for fallback: empty cache file yields empty string for header line check
            let first_line = lines.next().unwrap_or_default();
            if first_line == header_prefix {
                for line in lines {
                    let parts: Vec<&str> = line.split('\t').collect();
                    if let [p0, p1, p2] = parts.as_slice() {
                        if let (Ok(mtime), Ok(size)) = (p1.parse(), p2.parse()) {
                            cache.insert((*p0).to_string(), (mtime, size));
                        }
                    }
                }
            }
        }
    }

    let mut updated_cache = cache.clone();

    // 2. Discover test_*.rs files (excluding already generated files)
    for entry in WalkDir::new(src_dir) {
        let entry = entry?;
        let path = entry.path();

        if !path.is_file() {
            continue;
        }

        let file_name = path
            .file_name()
            .and_then(|s| s.to_str())
            // Reason for fallback: non-UTF-8 filenames are skipped during discovery
            .unwrap_or_default();

        if !file_name.starts_with("test_") || !file_name.ends_with(".rs") {
            continue;
        }

        // Skip files that are already generated
        if file_name.ends_with(".generated.rs") {
            continue;
        }

        stats.total_discovered = stats.total_discovered.saturating_add(1);

        let stem = path
            .file_stem()
            .and_then(|s| s.to_str())
            // Reason for fallback: non-UTF-8 stem defaults to empty string
            .unwrap_or_default();

        let target_name = format!("{stem}.generated.rs");
        let target_path = out_dir.join(&target_name);

        let metadata = fs::metadata(path)?;
        let mtime = metadata
            .modified()?
            .duration_since(UNIX_EPOCH)
            // Reason for fallback: files modified before UNIX epoch default to zero timestamp
            .unwrap_or_default()
            .as_nanos();
        let size = metadata.len();

        let rel_key = path
            .strip_prefix(src_dir)
            // Reason for fallback: path not sharing prefix remains unchanged
            .unwrap_or(path)
            .to_string_lossy()
            .to_string();

        // 3. Cache hit check
        if !force && target_path.exists() {
            if let Some((cached_mtime, cached_size)) = cache.get(&rel_key) {
                if *cached_mtime == mtime && *cached_size == size {
                    stats.cache_hits = stats.cache_hits.saturating_add(1);
                    continue;
                }
            }
        }

        // 4. Regenerate content
        let content = fs::read_to_string(path)?;
        let transformed = transform_test_content(file_name, &content)?;

        write_if_changed(&target_path, &transformed)?;
        updated_cache.insert(rel_key, (mtime, size));
        stats.generated_count = stats.generated_count.saturating_add(1);
    }

    // 5. Write updated build cache
    let mut cache_str = format!("# source_hash\t{source_hash}\n");
    let mut sorted_keys: Vec<_> = updated_cache.keys().cloned().collect();
    sorted_keys.sort();
    for k in sorted_keys {
        if let Some((mtime, size)) = updated_cache.get(&k) {
            cache_str.push_str(&format!("{k}\t{mtime}\t{size}\n"));
        }
    }
    write_if_changed(cache_file, &cache_str)?;

    Ok(stats)
}

/// Deletes the upstream test files that have been verified to have matching
/// `.generated.rs` files, explicitly preserving any files that omit the autogenerated
/// marker.
pub fn remove_verified_autogenerated_originals(tests_dir: &Path) -> Result<usize> {
    let mut removed_count: usize = 0;

    for entry in WalkDir::new(tests_dir) {
        let entry = entry?;
        let path = entry.path();

        if !path.is_file() {
            continue;
        }

        let file_name = path
            .file_name()
            .and_then(|s| s.to_str())
            // Reason for fallback: non-UTF-8 filenames are skipped during discovery
            .unwrap_or_default();

        if !file_name.starts_with("test_") || !file_name.ends_with(".rs") {
            continue;
        }

        // Never touch generated files
        if file_name.ends_with(".generated.rs") {
            continue;
        }

        let stem = path
            .file_stem()
            .and_then(|s| s.to_str())
            // Reason for fallback: non-UTF-8 stem defaults to empty string
            .unwrap_or_default();

        let target_generated = tests_dir.join(format!("{stem}.generated.rs"));

        // Only consider deletion if the replacement .generated.rs exists
        if !target_generated.exists() {
            continue;
        }

        // Check if this file has the autogenerated marker
        let content = fs::read_to_string(path)?;
        if !has_autogenerated_marker(&content) {
            // Preserve files that omit the marker
            continue;
        }

        // Remove the verified original autogenerated file explicitly
        fs::remove_file(path)?;
        removed_count = removed_count.saturating_add(1);
    }

    Ok(removed_count)
}

