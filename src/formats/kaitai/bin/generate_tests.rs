//! CLI tool to regenerate Kaitai Struct test files to meet ctoolbox repository
//! standards (.generated.rs naming, #[crate::ctb_test], and safe conversions).

#[allow(
    unused_imports,
    clippy::wildcard_imports,
    reason = "Standard workspace binary prelude"
)]
use ctb_utilities::*;

use std::path::PathBuf;
use clap::Parser;
use ctb_formats_kaitai::codegen::test_generator::{
    regenerate_tests, remove_verified_autogenerated_originals,
};

/// CLI options for Kaitai Struct test regeneration.
#[derive(Parser, Debug)]
#[command(
    author,
    version,
    about = "Regenerate Kaitai Struct tests to meet repository standards"
)]
struct Cli {
    /// Directory containing upstream test files.
    #[arg(long, value_name = "TESTS_DIR")]
    tests_dir: Option<PathBuf>,

    /// Destination directory for .generated.rs test files.
    #[arg(long, value_name = "OUT_DIR")]
    out_dir: Option<PathBuf>,

    /// Path to the .build_cache file.
    #[arg(long, value_name = "CACHE_FILE")]
    cache_file: Option<PathBuf>,

    /// Force regeneration of all test files, ignoring the build cache.
    #[arg(long)]
    force: bool,

    /// Clean verified autogenerated original test files after generation.
    /// Files that omit the autogenerated comment are preserved.
    #[arg(long)]
    clean_old: bool,
}

fn main() -> Result<()> {
    let cli = Cli::parse();

    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let default_tests_dir = manifest_dir.join("kaitai_struct_tests/spec/rust/tests");

    let tests_dir = cli.tests_dir.unwrap_or(default_tests_dir);
    let out_dir = cli.out_dir.unwrap_or_else(|| tests_dir.clone());
    let cache_file = cli
        .cache_file
        .unwrap_or_else(|| out_dir.join(".build_cache"));

    log!(
        "Regenerating Kaitai tests from {} into {}",
        tests_dir.display(),
        out_dir.display()
    );

    let stats = regenerate_tests(&tests_dir, &out_dir, &cache_file, cli.force)?;

    println!(
        "Kaitai test regeneration complete: {} generated, {} cache hits ({} discovered)",
        stats.generated_count,
        stats.cache_hits,
        stats.total_discovered
    );

    if cli.clean_old {
        let removed = remove_verified_autogenerated_originals(&tests_dir)?;
        println!(
            "Removed {} verified autogenerated original test files (preserved non-autogenerated files)",
            removed
        );
    }

    Ok(())
}

