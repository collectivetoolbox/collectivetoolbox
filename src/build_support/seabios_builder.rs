#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Symbol {
    pub name: String,
    pub offset: usize,
    pub size: usize,
    pub section_name: Option<String>,
    pub fileid: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Reloc {
    pub offset: usize,
    pub reloc_type: String,
    pub symbolname: String,
}

#[derive(Debug, Clone)]
pub struct Section {
    pub name: String,
    pub size: usize,
    pub align: usize,
    pub fileid: String,
    pub category: String,
    pub finalloc: Option<usize>,
    pub finalsegloc: usize,
    pub relocs: Vec<Reloc>,
}

