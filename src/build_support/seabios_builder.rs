pub const BUILD_LOWRAM_END: usize = 0xa0000;
pub fn run_ldnoexec(infile: &Path, outfile: &Path) -> Result<()> {
    let mut data = fs::read(infile)
        .with_context(|| format!("Failed to read {}", infile.display()))?;
    if let Some(elem) = data.get_mut(16) {
        *elem = 0x01;
    }
    if let Some(parent) = outfile.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(outfile, data)
        .with_context(|| format!("Failed to write {}", outfile.display()))?;
    Ok(())
}

fn alignpos(pos: usize, alignbytes: usize) -> usize {
    if alignbytes == 0 {
        return pos;
    }
    let mask = alignbytes.saturating_sub(1);
    (pos.saturating_add(mask)) & !mask
}

fn _aligndown(pos: usize, alignbytes: usize) -> usize {
    if alignbytes == 0 {
        return pos;
    }
    let mask = alignbytes.saturating_sub(1);
    pos & !mask
}

pub fn run_buildversion(args: &[String]) -> Result<()> {
    let mut outfile = String::new();
    let mut extraversion = String::new();
    let mut tools = String::new();

    let mut i = 0;
    while i < args.len() {
        match args.get(i).map(String::as_str) {
            Some("-e") => {
                if i.saturating_add(1) < args.len() {
                    if let Some(val) = args.get(i.saturating_add(1)) {
                        extraversion = val.clone();
                    }
                    i = i.saturating_add(1);
                }
            }
            Some("-t") => {
                if i.saturating_add(1) < args.len() {
                    if let Some(val) = args.get(i.saturating_add(1)) {
                        tools = val.clone();
                    }
                    i = i.saturating_add(1);
                }
            }
            Some(arg) if !arg.starts_with('-') => {
                outfile = arg.to_string();
            }
            _ => {}
        }
        i = i.saturating_add(1);
    }

    if outfile.is_empty() {
        bail!("buildversion: missing output header file argument");
    }

    let version = format!("rel-1.16.2{extraversion}");
    let tools_str = if tools.is_empty() {
        "gcc binutils".to_string()
    } else {
        tools
    };

    let content = format!(
        "/* DO NOT EDIT! This is an autogenerated file. See seabios-tool. */\n\
         #define BUILD_VERSION \"{version}\"\n\
         #define BUILD_TOOLS \"{tools_str}\"\n"
    );

    if let Some(parent) = Path::new(&outfile).parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&outfile, content)?;
    println!("Version: {version}");
    Ok(())
}

pub fn run_vgafixup(infilename: &Path, outfilename: &Path) -> Result<()> {
    let content = fs::read_to_string(infilename)
        .with_context(|| format!("Failed to read {}", infilename.display()))?;

    let mut out = Vec::new();
    for line in content.lines() {
        let sline = line.trim();
        if sline == "ret" {
            out.push("retw $2".to_string());
        } else if sline == "leave" {
            out.push("movl %ebp, %esp ; popl %ebp".to_string());
        } else if sline.starts_with("call") {
            let rest = sline.get(4..).unwrap_or("");
            out.push(format!("pushw %ax ; callw{rest}"));
        } else if sline.starts_with("leal") {
            out.push(handle_leal(sline));
        } else {
            out.push(line.to_string());
        }
    }

    if let Some(parent) = outfilename.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(outfilename, format!("{}\n", out.join("\n")))?;
    Ok(())
}

fn handle_leal(sline: &str) -> String {
    let rest = sline.get(4..).unwrap_or("").trim();
    if rest.contains("(%esp)") {
        return format!("leaw {}", rest.replace("%e", "%"));
    }
    format!("movl %ebp, %esp ; {sline}")
}

pub fn run_buildrom(inname: &Path, outname: &Path) -> Result<()> {
    let mut data = fs::read(inname)
        .with_context(|| format!("Failed to read {}", inname.display()))?;

    let count = data.len();
    let target_len = alignpos(count, 512);
    data.resize(target_len, 0);
    let count = data.len();

    if data.len() >= 26 {
        let pci1 = usize::from(data.get(24).copied().unwrap_or(0));
        let pci2 = usize::from(data.get(25).copied().unwrap_or(0));
        #[expect(
            clippy::expect_used,
            reason = "Shift of 8 bits fits within usize width (32/64 bit)"
        )]
        let pcidata =
            pci1 | (pci2.checked_shl(8).expect("8-bit shift fits in usize"));
        if pcidata != 0 && data.len() >= pcidata.saturating_add(18) {
            #[expect(
                clippy::expect_used,
                reason = "Division by constant 512 is non-zero and cannot fail"
            )]
            let count_blocks = count.checked_div(512).expect("512 is non-zero");
            let blocks = u16::try_from(count_blocks).unwrap_or(0).to_le_bytes();
            if let Some(slot) = data.get_mut(pcidata.saturating_add(16)) {
                *slot = blocks.first().copied().unwrap_or(0);
            }
            if let Some(slot) = data.get_mut(pcidata.saturating_add(17)) {
                *slot = blocks.get(1).copied().unwrap_or(0);
            }
        }
    }

    if data.len() >= 7 {
        if let Some(slot) = data.get_mut(2) {
            #[expect(
                clippy::expect_used,
                reason = "Division by constant 512 is non-zero and cannot fail"
            )]
            let count_blocks = count.checked_div(512).expect("512 is non-zero");
            *slot = u8::try_from(count_blocks).unwrap_or(0);
        }
        if let Some(slot) = data.get_mut(6) {
            *slot = 0;
        }

        let cksum: usize = data.iter().map(|&b| usize::from(b)).sum();
        let ckbyte = u8::try_from(
            (0x100_usize.saturating_sub(cksum.rem_euclid(256))).rem_euclid(256),
        )
        .unwrap_or(0);
        if let Some(slot) = data.get_mut(6) {
            *slot = ckbyte;
        }
    }

    if let Some(parent) = outname.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(outname, data)?;
    Ok(())
}

pub fn run_checkrom(
    _objinfo: &Path,
    finalsize_kb: usize,
    rawfile: &Path,
    outfile: &Path,
) -> Result<()> {
    let rawdata = fs::read(rawfile)
        .with_context(|| format!("Failed to read {}", rawfile.display()))?;

    let datasize = rawdata.len();
    let mut finalsize = finalsize_kb.saturating_mul(1024);
    if finalsize == 0 {
        finalsize = 64_usize.saturating_mul(1024);
        if datasize > 64_usize.saturating_mul(1024) {
            finalsize = 128_usize.saturating_mul(1024);
            if datasize > 128_usize.saturating_mul(1024) {
                finalsize = 256_usize.saturating_mul(1024);
            }
        }
    }

    if datasize > finalsize {
        bail!("ROM size error: {datasize} > {finalsize}");
    }

    let mut out = vec![0_u8; finalsize.saturating_sub(datasize)];
    out.extend_from_slice(&rawdata);

    let free = finalsize.saturating_sub(datasize);
    let datasize_u32 = u32::try_from(datasize).unwrap_or(u32::MAX);
    let finalsize_u32 = u32::try_from(finalsize).unwrap_or(u32::MAX);
    let datasize_f = f64::from(datasize_u32);
    let finalsize_f = f64::from(finalsize_u32);
    let pct = if finalsize_f > 0.0 {
        (datasize_f / finalsize_f) * 100.0
    } else {
        0.0
    };
    let kb = finalsize.checked_div(1024).unwrap_or(0);
    println!(
        "Total size: {datasize}  Fixed: {datasize}  Free: {free} (used {pct:.1}% of {kb}KiB rom)"
    );

    if let Some(parent) = outfile.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(outfile, out)?;
    Ok(())
}

